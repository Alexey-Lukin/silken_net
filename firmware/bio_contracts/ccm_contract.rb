# =========================================================================
# ⚖️ ABI ратифіковано founder 2026-10-10 (врізка 03_04 §7.3): контракт отримує РІВНО
# 14 байт CCM-plaintext, які сервер автентифікує й розпаковує (байт статусу — нуль:
# його повертає сам контракт), і повертає одне ціле — байт статусу. C-міст OTA не
# оновлює, тож цю сигнатуру фліп FW.2 заморожує на все життя польових вузлів; зате
# контракт, що бачить ті самі байти, може OTA-оновленням відзеркалити будь-яку майбутню
# серверну формулу над полями дроту.
#
# Точка входу — ВЛАСНА для ери (`ccm_state`, не `calculate_state`): контракт ECB-ери на
# CCM-вузлі падає NoMethodError-ом, а не біжить із чужими аргументами. Еру контракту в
# БД звіряє з пульсом Королев диспетчер OTA (`bio_contract_firmwares.wire_era`).
#
# Байт статусу CCM-ери (⚖️ коди делеговано 2026-10-10, 03_05 §2.1): status 0 — контракт
# відпрацював (тому старші біти тут нулі); 3 (vm_error) пише C-міст на збої; 1 і 2 —
# резерв, бекенд читає їх як порушення відповідності. Бали — заява для тесту
# відповідності серверному перерахунку (`expected_homeostasis_gp`, «утримання» GP).
# Формула — metabolic_core.rb (mrbc компілює її разом із цим файлом).
#
# Байти 12..13 — EMA-вхід балів (BE, «wire = вхід GP» E.63 (г)) за розкладкою
# Pack_CCM_Sensor_Payload (firmware/common/lora_ccm.h); золотий вектор G_PT_REV22
# пінить зсув з обох боків (firmware/test/test_bytecode_vm.c · attractor_spec).
# ⚠️ Без модуля й іменованих констант СВІДОМО: кожен символ — байти в irep, а контракт
# має вкластися в стелі OTA Солдата (FW.67): gen_bytecode.sh друкує розмір, а гейт —
# диспетчер OTA й пін «fits the real CCM-era contract…» (deployment_dispatcher_service_spec).
# =========================================================================
def ccm_state(pt)
  SilkenNet::Metabolic.homeostasis_gp((pt.getbyte(12) << 8) | pt.getbyte(13))
end
