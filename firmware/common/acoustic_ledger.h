/*
 * acoustic_ledger.h — [ARCH.102] Лічильник акустичних подій як ЛЕДЖЕР
 * (One-Home: Soldier і host-тести компілюють цей самий предикат — без копій).
 *
 * Доти лічильник обнулявся у Фазі 2, тобто на КОЖНОМУ проході циклу, ще до
 * того, як стане відомо, чи кадр узагалі поїде. Два наслідки, обидва тихі:
 *
 *   (1) на дроті величина була рівно 0 або 1, бо на пробудження припадає
 *       щонайбільше один інференс — а σ-таблиця (03_04) і бекендні пороги
 *       писалися під семантику «подій за інтервал». Порівняння з порогом,
 *       більшим за 1, було недосяжним із реального заліза;
 *   (2) подія, зафіксована в циклі, який відклав TX по морозу
 *       (`Should_Defer_TX`) або відправив grace-hello замість телеметрії,
 *       ЗНИКАЛА — знімок уже обнулив лічильник, а кадр не поїхав.
 *
 * Ледж-дисципліна знімає обидва: споживає рівно те, що доставлено, і лишає
 * решту жити до наступного успішного uplink'а. Незʼїдений залишок доживає до
 * Кенозису й лягає в DR0 разом із рештою стану, тож переживає STOP2.
 *
 * ⚠️ Стеля названа: `uint8_t` насичується на 255 (той самий інкремент, що й
 * доти), а 0xFE/0xFF зарезервовані як сентинели ARCH.41-B/panic — тобто
 * ледж рахує ПОДІЇ, а не час, і довга серія відкладених TX упирається в
 * стелю типу, не в помилку. Розрізнення «255 подій» ⊥ «сентинел» лишається
 * за `Soldier_Acoustic_Wire_Value`, цей заголовок його не дублює.
 */

#ifndef SILKEN_ACOUSTIC_LEDGER_H
#define SILKEN_ACOUSTIC_LEDGER_H

#include <stdint.h>

/*
 * Скільки лишити в лічильнику після успішної передачі `delivered` подій.
 * Віднімання, а не обнулення: між знімком і передачею лічильник у поточній
 * конструкції не росте, але віднімання лишається правдивим і тоді, коли це
 * зміниться. Гард `>=` робить функцію тотальною — від'ємного залишку немає.
 */
static inline uint8_t Acoustic_Ledger_Consume(uint8_t counter, uint8_t delivered)
{
    return (delivered >= counter) ? 0u : (uint8_t)(counter - delivered);
}

#endif /* SILKEN_ACOUSTIC_LEDGER_H */
