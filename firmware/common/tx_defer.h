/*
 * tx_defer.h — [FW.10] Зимовий кенозис передачі (One-Home: Soldier-глю
 * та host-тести компілюють цей самий предикат — без копій).
 *
 * При лютому морозі ESR іоністора різко зростає; LoRa-TX при кволій
 * напрузі кинув би ксилему у брауноут. Краще промовчати й зберегти тепло
 * (канон 03_01 §1.8а «Кенозис холодом»). Задум — кон'юнкція: холод І
 * низька напруга; тепле дерево при низькому Vcap ще передає.
 *
 * ⚠️ [ARCH.99] СТЕЛЯ, яку цей заголовок доти заперечував («обидві умови
 * несучі»): виклик годує `vcap_voltage` = мВ VDDA (Adc_Vdda_Mv, FW.50), а
 * ту шину BQ25570 стабілізує на 3.3 В (02_03 §7) — тож `< 4000` істинне
 * ЗАВЖДИ, поки buck тримає, і предикат у полі тотожний `temp < −15`.
 * Клауза «холодне, але заряджене дерево передає» недосяжна за побудовою.
 * Це четвертий гейт на цій шині: сусідні три (VCAP_LISTEN_THRESHOLD 2800,
 * FAUNA_VCAP_MIN_MV 4500, CAD_PANIC_PREAMBLE_VCAP_MIN_MV 4500) своє
 * виродження оголошують — цей мовчав. Напрямок безпечний (вузол мовчить
 * там, де міг би передати: втрата зимової телеметрії, не шкода залізу),
 * панічний тракт не зачеплено (panic_payload іде повз цей предикат).
 * Присуд про саме число — 00_07 ARCH.99 ⚖️, разом із живим Vcap-каналом.
 * ⚠️ Host-сюїта на цю вісь зелена й РОЗРІЗНЯЛЬНА (входи 4000/4001/5000):
 * функція правильна, неіснує саме такий вхід — не читай її як доказ поля.
 *
 * Поріг температури суворо `<` (не `<=`): рівно −15°C холодом не
 * вважається — freeze-contract проти випадкової зміни оператора. Саме
 * тому предикат живе тут host-testable швом, а не анонімним виразом:
 * розсинхрон порогу чи оператора не пройде повз сюїту (test_soldier_logic).
 */

#ifndef SILKEN_TX_DEFER_H
#define SILKEN_TX_DEFER_H

#include <stdint.h>

/* Стеля морозу, °C — нижче неї ESR іоністора небезпечний для TX. */
#define COLD_TX_DEFER_TEMP        (-15)
/* Стеля напруги, мВ — нижче неї TX ризикує брауноутом ксилеми. */
#define COLD_TX_DEFER_VCAP_MV     4000

/*
 * Чи пропустити TX-вікно цього пробудження. 1 = відкласти (падаємо у
 * Кенозис, Фаза 5). Обидві умови несучі — кон'юнкція, не диз'юнкція.
 */
static inline int Should_Defer_TX(int8_t temp, uint16_t vcap_mv)
{
    return (temp < COLD_TX_DEFER_TEMP && vcap_mv < COLD_TX_DEFER_VCAP_MV);
}

#endif /* SILKEN_TX_DEFER_H */
