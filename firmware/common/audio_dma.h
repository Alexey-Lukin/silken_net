/*
 * audio_dma.h — [ARCH.102] Межі аудіо-вікна: чи є ЧИМ міряти і скільки
 * чекати (One-Home: Soldier і host-тести компілюють ці самі предикати).
 *
 * Доти Фаза 1.5 стартувала конвеєр беззастережно й чекала прапорця у
 * `while (!audio_ready)` без стелі. Обидві половини вбивчі на кремнії:
 *
 *   (1) `HAL_ADC_Start_DMA` розіменовує `hadc->DMA_Handle` ДО будь-якої
 *       перевірки (vendored `stm32wlxx_hal_adc.c` — три присвоєння
 *       XferCallback'ів), тож незалінкований DMA дає не `HAL_ERROR`, а
 *       запис за NULL → HardFault, а не «поганий вимір»;
 *   (2) навіть із живим DMA нічого не вивело б ядро зі SLEEP, якби
 *       метроном мовчав — і незакінчене вікно з'їдало б IWDG-вікно
 *       (~26 с, 03_01 §1.3) на КОЖНІЙ п'єзо-події, тобто ребут замість
 *       виміру, а з ним і втрата RAM-лічильників та OTA-збірки.
 *
 * Тому рішення «міряли чи ні» стоїть ПЕРЕД HAL'ом і має рівно одну
 * посадку: будь-яка з трьох відмов (периферії немає · старт відмовив ·
 * дедлайн вичерпано) лишає прапорець в `AUDIO_DMA_IDLE`, і інференс не
 * біжить. Це та сама дисципліна, що `DELTA_T_UNKNOWN_S` (E.63): невимір
 * мусить бути ВІДРІЗНЯЛЬНИМ станом, а не значенням, схожим на вимір.
 *
 * ⚠️ Стеля названа й вона не знімається кодом: `MX_ADC_Init`/`MX_TIM2_Init`
 * лишаються порожні до board-freeze (FW.46 — пін-мапа, клок-дерево й сам
 * ADC-канал аудіо-входу є фізикою, якої в каналній карті 03_01 ще немає),
 * тож на сьогоднішньому кремнії гейт (1) закритий і тракт чесно НЕ міряє.
 * `acoustic_events` з поля доти джерела не має — це вже ратифіковано в
 * 03_03 §2.1 і цим заголовком не змінюється.
 */

#ifndef SILKEN_AUDIO_DMA_H
#define SILKEN_AUDIO_DMA_H

#include <stdint.h>
#include <stddef.h>

/*
 * Стани прапорця вікна. `DONE == 1` свідомо: старе `audio_ready = 1`
 * лишається бітово тим самим значенням, тож жоден читач не зсунувся.
 */
#define AUDIO_DMA_IDLE   0u  /* вікно не зняте — сюди ж падають УСІ три відмови */
#define AUDIO_DMA_DONE   1u  /* DMA дописав останній семпл: буфер придатний */
#define AUDIO_DMA_ERROR  2u  /* ADC overrun / DMA transfer-error: буфер НЕ придатний */

/*
 * Бюджет очікування вікна, мс. Номінал = 512 семплів / 16 кГц = 32 мс
 * (03_03 §2.1), тож 250 мс — восьмикратний запас на джитер метронома й
 * лишається ~1% IWDG-вікна: скільки б п'єзо-подій не прийшло за цикл,
 * сторожовий пес більше не може бути з'їдений аудіо-трактом.
 */
#define AUDIO_DMA_TIMEOUT_MS  250u

/*
 * Чи можна взагалі торкатись HAL-конвеєра. Гейт стоїть до першого виклику
 * саме тому, що `HAL_ADC_Start_DMA` не переживає жодного з трьох NULL'ів
 * (див. шапку). Аргументи — `const void *`, щоб предикат не тягнув HAL і
 * компілювався в host-сюїту разом із прошивкою.
 */
static inline int Audio_Dma_Peripherals_Ready(const void *adc_instance,
                                              const void *tim_instance,
                                              const void *dma_instance)
{
    return (adc_instance != NULL && tim_instance != NULL && dma_instance != NULL);
}

/*
 * Чи вичерпано бюджет очікування. Віднімання беззнакове й тому переживає
 * 49-денне перевертання `HAL_GetTick` — різниця лишається правдивою через
 * межу, тоді як `now >= start + TIMEOUT` там дав би вічне очікування.
 */
static inline int Audio_Dma_Wait_Expired(uint32_t start_tick, uint32_t now_tick)
{
    return ((uint32_t)(now_tick - start_tick) >= AUDIO_DMA_TIMEOUT_MS);
}

#endif /* SILKEN_AUDIO_DMA_H */
