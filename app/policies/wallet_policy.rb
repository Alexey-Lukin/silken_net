# frozen_string_literal: true

class WalletPolicy < ApplicationPolicy
  def index?
    true
  end

  # [SEC.25 Ф2] Роль тут більше не дає доступу — лише організація, в контексті якої
  # виконується запит. Раніше рядок вів `super_admin? ||`, тобто платформена роль
  # відмикала скарбницю БУДЬ-ЯКОЇ організації; тепер super_admin бачить рівно ту, в
  # яку перемкнувся, і по тому самому правилу, що всі.
  #
  # 🔴 Знімати цю гілку МОЖНА ЛИШЕ ПАРОЮ зі `Scope` — вони одна конструкція. Звузити
  # сам `Scope` й лишити її тут = `wallets#index` віддає лише свою організацію, а
  # `GET /wallets/:id` і далі будь-чию, бо контролер вантажить запис голим
  # `Wallet.find(params[:id])` (три екшени: show/balance/metadata). Це фікс, що
  # відвантажується з ілюзією ізоляції — рівно та форма, від якої цей файл уже
  # лікували в SEC.16, тільки роллю вище.
  def show?
    same_organization?(record.organization_id) ||
      same_organization?(record.tree&.cluster&.organization_id)
  end

  def balance?
    show?
  end

  def metadata?
    show?
  end

  # [I18N.2] Комірка статусу транзакції — той самий обʼєкт і те саме право, що
  # сторінка гаманця. Окремого правила для транзакції СВІДОМО немає: воно було б
  # другим означенням тенантності поруч із `show?`, а ці двоє вже мають прецедент
  # розходження (`BlockchainTransactionsController#find_transaction` скоупить лише
  # через `wallet → tree → cluster`, тоді як `show?` приймає ще й пряме
  # `wallet.organization_id`).
  def transaction_status?
    show?
  end

  class Scope < ApplicationPolicy::Scope
    # [ARCH.87] Дзеркалить ОБИДВІ гілки `show?` — доти приймалась лише перша, і це
    # була не діра безпеки (скоуп вужчий за право), а діра ВИДИМОСТІ: гаманець із
    # порожнім `organization_id` зникав зі списку й із суми ліквідності, а за прямою
    # адресою відкривався нормально. Тобто список і пряма адреса відповідали на
    # питання «чий це гаманець» по-різному — рівно те розходження, від якого шапка
    # цього файлу застерігає («одна конструкція, знімати лише парою»).
    #
    # Обидві гілки звіряються з ОДНІЄЮ організацією запиту, тож ширшим тенант-периметр
    # не стає. Однозначність `OR` тримає інваріант «денормалізована колонка ніколи не
    # розходиться з ланцюгом» — він не декларативний: `clusters.id` фабрично заморожено
    # (HKDF-salt у кремнії), тож переїзд дерева між кластерами не існує як операція
    # (⚖️ 2026-07-30), а носій інваріанта — `spec/quality/wallet_org_denormalization_spec.rb`.
    #
    # ⚠️ [UI.7] Гард на порожній контекст тут НЕ надлишковий, хоч `for_organization`
    # і будує сирий `= :org`, який на `nil` не істинний ніколи: fail-closed там є
    # властивістю ФОРМИ запиту, не правила, тож перша ж переписка ланцюга на
    # хеш-форму (`where(organization_id: org_id)` → `IS NULL`) мовчки відкрила б
    # org-less гаманці. Правило мусить бути оголошене, а не успадковане від SQL.
    def resolve
      return scope.none if no_acting_organization?

      scope.for_organization(organization_id)
    end
  end
end
