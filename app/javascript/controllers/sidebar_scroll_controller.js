import { Controller } from "@hotwired/stimulus"

// Тримає власну скрол-позицію сайдбара через Turbo Drive-візит.
//
// Предмет: `<aside>` меню є ВЛАСНИМ скрол-контейнером (`overflow-y-auto` +
// `md:h-screen`), бо 21 пункт у чотирьох секціях не вміщається у вьюпорт. Drive-візит
// підміняє `<body>` цілком, тож свіжий вузол приходить зі `scrollTop = 0` — людина,
// що проскролила меню й клікнула нижній пункт, діставала меню «перемотаним» угору.
//
// 🔴 Чому носієм став контролер, а не два очевидніші важелі — обидва вже виміряні
// й закриті в `04_04 §8`:
//   * `data-turbo-permanent` — скрол НЕ рятує (виміряно браузером: `scrollTop`
//     150 → 0 через візит), а крім того заборонений цим деревом із нульовим
//     винятком (гейт `spec/quality/no_turbo_permanent_spec.rb`, [UI.11]).
//   * `turbo-refresh-scroll: preserve` — метатег у `DashboardLayout` стоїть, але
//     для ЦЬОГО контейнера він декоративний: Turbo скролить `window`, а `body`
//     має `overflow-hidden`. Під морфом скрол зберігається сам (вузол переживає
//     рендер), тож контролер потрібен рівно для НАВІГАЦІЇ — тієї половини
//     візитів, якої метатег не накриває за побудовою.
//
// Стан живе в модульній змінній, а не в `sessionStorage`, навмисно: її час життя
// дорівнює часу життя JS-контексту Turbo-сесії, тож «повне перезавантаження
// скидає скрол» виходить безплатно — без ключа, без serialize і без гілки на
// заблоковане сховище.
let rememberedScrollTop = 0

export default class extends Controller {
  // ⚠️ Обидва інстанси сайдбара (десктопний + мобільна шухляда рендерять ОДИН
  // компонент) ділять цю змінну, і це безпечно ЗА ФІЗИКОЮ, а не за домовленістю:
  // на кожному вьюпорті видимий рівно один із них, а невидимий (`hidden md:block`
  // обгортка на телефоні; `md:hidden` + закритий `<dialog>` на десктопі) не має
  // scroll box узагалі — тож `scroll` на ньому не фіриться, і записати нуль поверх
  // чужої позиції він не може. Саме тому слухач висить на ЕЛЕМЕНТІ, а не на
  // `document`: подія Turbo долетіла б і до невидимого інстанса, і гейт на
  // видимість довелось би писати умовою, яку можна забути.
  connect() {
    // Ідемпотентно: за один візит Turbo кличе `connect()` двічі, коли показує
    // кешований preview перед свіжим рендером. Присвоєння браузер клампить до
    // реального максимуму, тож коротший сайдбар не дає позиції поза межами.
    this.element.scrollTop = rememberedScrollTop

    this.remember = () => { rememberedScrollTop = this.element.scrollTop }
    this.element.addEventListener("scroll", this.remember, { passive: true })
  }

  disconnect() {
    this.element.removeEventListener("scroll", this.remember)
  }
}
