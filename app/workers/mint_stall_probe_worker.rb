# = ===================================================================
# 📏 MINT STALL PROBE (ARCH.94 detector — досяжний дім)
# = ===================================================================
# Знімає глибину застряглої емісії: скільки гаманців стоять над порогом, не
# давши мінту. Прилад, не гроші — нічого не мутує, лише `.set` на gauge.
#
# 🔴 **Чому дім тут, а не в `TokenomicsBatchCallbacks`, звідки семпл переїхав.**
# Канон `04_02` DOC-R.10 казав «перенести його НЕ можна: обґрунтування ARCH.94
# (після здорового циклу eligible-множина порожня ЗА ПОБУДОВОЮ) істинне рівно в
# момент завершення батчу». Підставу переміряно 2026-08-25, і вона не тримається
# по трьох осях:
#
#   1. **Вибір не між колбеком і cron, а між НІЧИМ і cron.** `sidekiq-pro` поза
#      `Gemfile`, активний шим лише складає колбеки в масив — тобто писача в
#      проді не існує взагалі, і метрика стоїть порожня від народження.
#   2. **`on(:success)` — не «завершення батчу», а «завершення БЕЗ ПОМИЛОК».**
#      Джоба, що падає й вичерпує retry, дає `:complete`, ніколи `:success`. Отже
#      навіть із купленою ліцензією детектор застрягання мовчав би саме в тому
#      сценарії, заради якого існує: коли чанки емісії падають. Детектор, що
#      вимикається від власного предмета.
#   3. **Передумова ARCH.94 не потребує миті завершення.** `lock_and_mint!`
#      інкрементить `locked_balance` СИНХРОННО всередині `EvaluateTreeBatchWorker`
#      (не після on-chain мінту), тож гаманець виходить із множини в мить обробки
#      чанка. Здоровий годинний цикл спорожнює її задовго до наступного — а цей
#      прилад і знімає зріз перед ним (`55 * * * *`, `config/sidekiq.yml`).
#
# Тобто cron тут не слабший дублер, а СИЛЬНІШИЙ дім: він бачить клас «батч не
# дожив до успіху», недосяжний колбеку за побудовою.
class MintStallProbeWorker
  include Sidekiq::Job

  # `low` — прилад спостережності: він не сміє тіснити ані uplink, ані money-черги.
  # `retry: 1` — пропущений зріз не втрачає даних (наступний за годину), тож
  # наполегливий ретрай купував би лише шум.
  sidekiq_options queue: "low", retry: 1

  def perform
    depth = TokenomicsEvaluatorWorker.eligible_wallets.count
    SilkenNet::Metrics::MINT_ELIGIBLE_UNMINTED_DEPTH.set(depth)

    # Голос на нульовій дії — конвенція sweep/probe-воркерів [PERF.1]: тиша тут
    # означала б «прилад не біг», а це рівно те, що метрика мала б виявляти.
    Rails.logger.info "📏 [ARCH.94] Глибина застряглої емісії: #{depth} гаманців над порогом."
  rescue StandardError => e
    Rails.logger.warn "⚠️ [ARCH.94] Не вдалось зняти stall-глибину (мінт НЕ зачеплено): #{e.message}"
  end
end
