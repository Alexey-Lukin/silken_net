# =============================================================================
# 🔁 PEAQ BACKFILL — пускач для оголошеного recovery [ARCH.119]
# =============================================================================
# `PeaqRegistrationWorker` має рівно ОДИН enqueue-сайт — `ProvisioningController#register`,
# після коміту. Тобто спосіб відновлення не був «ручним», як у сусідів: його не було
# ЗОВСІМ. Дерево, чиї 5 ретраїв вичерпались (peaq RPC лежав) або чия нога була
# несконфігурована на мить провіжну, лишалось із `peaq_did = nil` **назавжди** — другої
# нагоди не наставало ніколи, бо провіжн трапляється один раз.
#
# 🔴 Клас — «механізм ⟷ його пускач»: механізм (реєстрація) справний, ідемпотентність
# справна (`peaq_did.present?` — рання відмова + повторна перевірка під `with_lock`),
# бракувало ПУСКАЧА. Доти `06_08 §2.2` крок 4 обіцяв «коли peaq оживає — реєстрація йде
# наступними retry/enqueue», тобто канон називав механізм, якого не існувало — рівно те,
# у чому сусідній крок 5 (IoTeX) уже зізнався й полагодив.
#
# ⚖️ **НЕ money-блокер, і це вирішує чергу й гучність.** Живий PATH 2-мінт peaq не
# гейтить (ARCH.53 §🗄️ — guard є KYC), тож дерево без DID мінтить нормально; діра
# лишається в ДОКАЗІ машинної ідентичності. Отже прилад спостережності: черга `low`,
# ніколи не тісниться з uplink/money.
#
# ⚠️ **Вікна ре-арму НЕМА, і це визначення предмета, а не пропуск.** IoTeX-сусід
# windows'иться, бо лог, незверифікований місяць, є предметом ретеншену; DID є ПОСТІЙНОЮ
# ідентичністю, тож дерево без нього лишається кандидатом скільки б не минуло. Стелю
# проходу тримає `BATCH_LIMIT`, а прогрес гарантує сама умова: успішна реєстрація
# виводить рядок із `peaq_did IS NULL`, тож множина дренажиться між прогонами.
class PeaqBackfillWorker
  include Sidekiq::Job

  # `low` + `retry: 1`: пропущений прохід не втрачає даних (наступний завтра),
  # наполегливий ретрай купував би лише шум на тлі того самого зовнішнього збою.
  sidekiq_options queue: "low", retry: 1

  # Стеля одного проходу. Кожне ре-армоване дерево — це джоба у `web3`, тож прохід
  # мусить не змогти залити чергу після довгого простою або пізньої активації ноги.
  BATCH_LIMIT = 500

  def perform
    # [ARCH.119] Activation gate з ГОЛОСОМ: ре-арм у несконфігуровану ногу — це не
    # recovery, це 500 × 6 провальних виконань щодоби назавжди. Рядок називає розмір
    # заборгованості, щоб стан був ВИДИМИЙ у логах, а не просто відсутній у них.
    unless Peaq::DidRegistryService.configured?
      pending = Tree.where(peaq_did: nil).count
      Rails.logger.warn "⏸️ [peaq Backfill] Нога не сконфігурована (PEAQ_NODE_URL/PEAQ_SIGNING_KEY) — " \
                        "#{pending} дерев лишаються без machine-identity DID; ре-арм відкладено до активації (06_04 §2.2)."
      return
    end

    ids = Tree.where(peaq_did: nil).order(:id).limit(BATCH_LIMIT).pluck(:id)
    return if ids.empty?

    ids.each { |id| PeaqRegistrationWorker.perform_async(id) }
    SilkenNet::Metrics::PEAQ_BACKFILL_REARMED_TOTAL.increment(by: ids.size)

    Rails.logger.warn "🔁 [peaq Backfill] Ре-армовано #{ids.size} дерев без peaq DID " \
                      "(стеля проходу #{BATCH_LIMIT})."
  end
end
