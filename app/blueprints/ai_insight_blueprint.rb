# 🔴 **Куплено класом «клієнт отримує ПОНАД те, що сторінка показує».** До цього
# блупринта `trees#show.json` віддавав `@insights` СИРОЮ реляцією, тобто сім
# рядків × девʼятнадцять колонок = 133 значення, з яких сторінка не показує
# жодного напряму. Серед них `fraud_detected` — антифрод-присуд, який HTML не
# має ВЗАГАЛІ (у хроніці він живе лише як гілка тексту й `severity: :critical`,
# ніколи як прапорець), `source_log_ids`, `model_source` і `recommendation`.
#
# ⚖️ **Присуд: стелею оголошено рівно те, що ВЖЕ друкує HTML.** Перелік узято
# з коду сторінок, не з інтуїції — `OracleVisions::ForecastCard` рендерить
# `insight_type` (через `insight_type_label`) · `target_date` · `summary` ·
# `probability_score` · `prediction_data.dig("yield_impact")`, а хроніка друкує
# прозою `stress_index` у відсотках.
#
# ⛔ **ДВІ JSONB-колонки свідомо НЕ віддаються блобом — `prediction_data` і
# `reasoning`.** Реєстр PII класифікує КОЛОНКИ й до ВМІСТУ JSONB сліпий за
# побудовою (скіл `backend` #80), тож віддати блоб означало б наново відкрити
# рівно той клас, проти якого стоїть цей файл: назовні пішло б усе, що туди
# колись покладуть. Тому `yield_impact` — ОГОЛОШЕНИЙ ключ, а не вибірка з блоба.
# `reasoning` не віддається зовсім: сторінка друкує ПРОЗУ, виведену з нього
# (`avg_z` · `max_temp` · `deviation_from_baseline`), а не самі значення.
#
# ⚠️ **Дзеркальна помилка того ж класу — звузити JSON НИЖЧЕ за показане**, і вона
# коштує стільки ж. Саме тому `stress_index` тут Є: людина бачить його у тексті
# хроніки, тож ховати його від клієнта означало б робити API біднішим за екран.
#
# 🔒 **Оголошена стеля цього файлу:** він судить ФОРМУ відповіді й нічого не каже
# про ПРАВО на неї — доступ дає асоціативний скоуп екшена (`acting_organization!`),
# і цей блупринт його не дублює. Дім рішення про маршрут і роль — `04_03 §4`, і
# він форми відповіді не документує ЗА ПОБУДОВОЮ (виміряно в SEC.36), тож єдині
# носії цього переліку — цей файл і його пін.
# =============================================================================
class AiInsightBlueprint < Blueprinter::Base
  identifier :id

  fields :insight_type, :target_date, :summary, :probability_score, :stress_index

  # ⛔ Один ОГОЛОШЕНИЙ ключ, ніколи весь `prediction_data`: блоб віддав би те,
  # чого ми не перелічували, а перелічити — і є вся суть цього файлу.
  field :yield_impact do |insight|
    insight.prediction_data&.dig("yield_impact")
  end
end
