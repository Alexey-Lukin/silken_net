# 🔴 Ключ `actuator:` у `actuators#show.json` віддавав СИРУ модель — усі
# одинадцять колонок, — і власний коментар екшена це оголошував: «ратифікованого
# переліку полів для `Actuator` у дереві немає (блупринта не існує), тож його
# звуження є ПРИСУДОМ, а не застосуванням». Присуд ухвалено; це файл-наслідок.
#
# 🔑 **Прецедент форми стояв у ТОМУ САМОМУ виклику:** сусідній ключ `history:`
# уже курований явним переліком, узятим із `command_status` (ендпоінт #49) ⊕
# `completed_at`. Дефектом було не «немає рішення», а те, що один ключ його не взяв.
#
# ⚖️ Стеля — рівно те, що друкує `Actuators::Card` (єдиний компонент HTML-гілки
# того ж екшена): `name` · `device_type` · `state` · `endpoint` ·
# `max_active_duration_s` · `estimated_mj_per_action` · `last_activated_at`.
# ⊕ `gateway_uid`, а НЕ `gateway_id`: сторінка показує саме `uid` асоціації, і
# звузити JSON нижче за показане — дзеркальна помилка того ж класу.
# ⛔ Не віддаються `created_at`/`updated_at`: сторінка їх не має, і клієнт, що
# на них зіпреться, зіпреться на те, чого ми не обіцяли.
#
# ⚠️ `idempotency_token` команд сюди не входить і входити не може — він живе на
# `actuator_commands`, і `command_status` свідомо його не пускає. Питання, чи є
# він чутливим САМ ПО СОБІ, лишається відкритим (`00_07` SEC.36 ⚖️); цей файл на
# нього не відповідає й не має вдавати, що відповів.
# =============================================================================
class ActuatorBlueprint < Blueprinter::Base
  identifier :id

  fields :name, :device_type, :state, :endpoint,
         :max_active_duration_s, :estimated_mj_per_action, :last_activated_at

  # ⚠️ Один додатковий запит на `show` — рівно той, що його вже робить HTML-гілка
  # того ж екшена. Дзеркалимо екран, а не оптимізуємо його.
  field :gateway_uid do |actuator|
    actuator.gateway&.uid
  end
end
