# [SEC.25 Ф2] Per-request контекст ВИКОНАВЦЯ — рівно стільки, скільки треба, щоб
# аудит міг сказати «цю дію зробили з перемкнутого контексту».
#
# 🔴 ЩО СЮДИ КЛАСТИ НЕ МОЖНА, і це головне про цей файл.
#
# Тут НЕМАЄ і не має бути `organization` як ДЖЕРЕЛА СКОУПУ. Скоуп даних живе в
# `BaseController#acting_organization` і доїжджає до Pundit явним `UserContext` —
# тобто передається аргументом, а не читається з повітря. Різниця не стилістична:
# амбієнтна організація доступна і в моделі, і в воркері, і всередині
# `Turbo::StreamsChannel.broadcast_*`, а там діє ПРОТИЛЕЖНЕ правило — броадкаст іде
# в організацію ВЛАСНИКА ресурсу (`cluster.organization_id`), не глядача. Один
# `Current.organization` у продюсері — і оновлення чужої організації поїдуть у стрім
# того, хто щойно перемкнув контекст. Тому тут лежать ЛИШЕ id, лише для сліду.
#
# Порожньо поза HTTP: Sidekiq виконує роботу в системному контексті, і `Current`
# там не виставляється — тобто відсутність мітки означає «системна дія», а не
# «мітку загубили».
class Current < ActiveSupport::CurrentAttributes
  # Організація, в контексті якої виконується запит.
  attribute :acting_organization_id
  # Власна (домашня) організація виконавця — та, що записана в `users`.
  attribute :home_organization_id

  # Дія виконується з ЧУЖОГО контексту: super_admin перемкнувся й діє в іншій
  # організації. Саме цей факт аудит і мусить зафіксувати — інакше організація
  # побачить наслідки (OTA-деплой, команду актуатору, зміну налаштувань) без сліду
  # про те, хто прийшов ззовні.
  def switched_context?
    acting_organization_id.present? && acting_organization_id != home_organization_id
  end
end
