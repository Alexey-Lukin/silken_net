module Telemetry
  # [SEC.42 (б)] Правдоподібність Σ delta_t: сирі delta_t кадрів дерева, що приїхали
  # одним конвертом, проти часу від його попереднього прийому. СПОСТЕРЕЖЕННЯ, не
  # вердикт (⚖️ делеговано, 03_05 §2.4): чесна втрата кадру й морозне відкладення TX
  # тягнуть частку вниз так само, як фальсифікатор із KEYL, що вкорочує delta_t, тож ні
  # алерту, ні грошової дії; гістограма збирає польовий розподіл для присуду, що ввімкне
  # строгість. Безключовий залишок — до секунди-двох на маяк: база delta_t іде за фактичним
  # кроком календаря (Silken_Beacon_Commit, wall_time.h).
  #
  # ⚠️ Стеля: «попередній прийом» — `Tree#last_seen_at`, тобто час ОБРОБКИ, і кадр чекає
  # флашу Королеви в її кеші, тож на каденсі, довшому за флаш, один відлік шумить на
  # фазі флашу в рази: тонкої підробки частка не бачить, у рази коротший СИРИЙ delta_t — бачить,
  # а правдоподібний сирий при балах-максимумі — ні: поля на дроті пишуться незалежно (це вісь
  # узгодженості EMA, лише CCM).
  # Відлік далеко над 1 дають ретрай частково закоміченого конверта (`since` — перша спроба)
  # і дві Королеви з тим самим деревом.
  module DeltaTCoverage
    # Коротший проміжок тоне в затримці черги `uplink`.
    MIN_ELAPSED_S = 60

    module_function

    # Частка — по ВИМІРЯНИХ кадрах: сентинел пропускається, сатурований дріт (0xFFFF, дріт u16)
    # уже є нижньою межею, тож кадр без виміру частку лише занижує, а не гасить (інакше фальсифікатор
    # засліплював би її одним сентинелом на конверт). nil — перший прийом, надто короткий
    # проміжок або жодного виміряного кадру.
    def ratio(delta_ts, since:, now:)
      return nil if since.nil?

      elapsed = now - since
      return nil if elapsed < MIN_ELAPSED_S

      measured = delta_ts.compact.reject { |dt| dt == SilkenNet::Attractor::DELTA_T_UNKNOWN_S }
      return nil if measured.empty?

      measured.sum / elapsed.to_f
    end
  end
end
