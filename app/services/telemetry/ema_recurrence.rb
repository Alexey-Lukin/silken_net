module Telemetry
  # [SEC.42 (б), друга вісь] Узгодженість EMA `delta_t` CCM-кадру з потоком сирих: на кадрах дерева із
  # суміжним FC сервер звіряє EMA на дроті з рекурентністю фільтра прошивки (`EMA_Update`,
  # `firmware/common/ema_filter.h`). Частка Σ (`DeltaTCoverage`) бачить лише фальсифікатора з KEYL, що
  # вкорочує СИРИЙ `delta_t`; бали ж рахуються з EMA (`ccm_growth_points`), а поля на дроті пишуться
  # незалежно — тож правдоподібний сирий при короткій EMA видно лише тут. СПОСТЕРЕЖЕННЯ, не вердикт (той
  # самий присуд, що й частка (б), 03_05 §2.4): ні алерту, ні грошової дії; гістограма збирає польовий
  # розподіл для присуду, що ввімкне строгість.
  #
  # Арифметика — дзеркало теплої гілки ×100 (α = 2/10). На дроті EMA = floor(×100 / 100) секунд, тож стан
  # попереднього кадру відомий лише до [100·e, 100·e + 99], і очікувана EMA — ціле в [lo, hi] завширшки
  # ≤ 1 с. Паритет із прошивкою пінить спек, що читає α з `ema_filter.h` і golden-таблиці з host-тесту
  # (`test_soldier_logic.c`: `golden_wire_sequence` · `warm_step_pins`), а не тримає власні копії.
  #
  # ⚠️ Стеля. Пару не судять (nil), коли висновку немає за побудовою: EMA попереднього кадру — сентинел
  # (прогрів, скид фільтра) чи сатурована; сирий кадру сатурований (дріт u16, а фільтр бере до 7 діб — пропуск
  # тут необхідний: сатурований сирий дав би хибне відхилення); EMA кадру — сентинел. Суміжність FC виключає
  # втрату кадру й паніку (обидві споживають FC), але не все, що рухає EMA повз кадри:
  #   · пробудження, що FC не спожило, — морозне відкладення TX (гоча `firmware` #4), grace-hello ARCH.41-C,
  #     невдала збірка кадру: ≈ 0.16·(r − EMA) на кожне, будь-якого знака, при стабільному каденсі — близько нуля;
  #   · 🔴 скид після PVD-коми: рятівник лишає в DR1 базу перерваного пробудження, а EMA в DR10/DR12 — з
  #     попереднього сну, тож перше пробудження після скиду годує фільтр ТРИВАЛІСТЮ КОМИ; коротка кома
  #     (секунди) дає ЧЕСНОМУ вузлу мінус у сотні-тисячі секунд — знак фальсифікатора, раз на брауноут
  #     (вада прошивки, не цієї перевірки: 00_07 FW.49);
  #   · скид після TX до Фази 5 (OTA APPLY, HardFault, канарка, IWDG): FC збережено, крок EMA — ні; наступний
  #     вимір від старої бази його компенсує, відхилення ≈ 0.16·(EMA − r).
  # Фальсифікатор, що тримає EMA коротшою за сирий, читається мінусом на кожній СУДЖЕНІЙ парі — але суміжність
  # обирає відправник: хто з KEYL крокує FC через один, пар не дає зовсім (вікно повтору приймає будь-який FC
  # вище за top), тож мовчання цієї осі не є виправданням вузла. «Останній рядок» — за `created_at`, тож
  # беклог кільця, що приїхав пізніше за живі кадри, лишає наступний живий кадр без пари (втрата, не хибна пара).
  # Епохи ключа рядок не несе: пара через межу епох потребувала б, щоб FC попереднього кадру був на 1 менший
  # за перший кадр нової, а з якорем `0x14` = 1 той перший — FC 2 (SEC.41); для вузла, провіжненого
  # по-старому (старт FC з HRNG), — точний збіг FC, ≈ 2⁻²⁴ на ре-провіжн.
  module EmaRecurrence
    ALPHA_NUM = 2
    ALPHA_DEN = 10
    SCALE     = 100     # EMA ×100 — одиниця DR10 і теплої гілки
    WIRE_MAX  = 0xFFFF  # дріт u16: сатурація і сирого, і EMA

    # Попередній кадр, старший за поріг ТИШІ платформи, не шукається: пара через тишу перетинає пробудження без
    # кадрів (мороз, кома), тож судити її було б гірше, ніж не судити. Для ЦЬОГО питання («кадр із FC − 1»)
    # межа відповіді не міняє — лише лишає таку пару без суду (на відміну від загального питання
    # `TelemetryLog.latest_per_tree`, шапка якого про це й попереджає), — і обрізає скан до свіжих партицій:
    # рядків на дерево у вікні ≈ поріг / каденс.
    PREVIOUS_FRAME_WINDOW = Tree::SILENCE_THRESHOLD

    module_function

    # Тепла гілка `EMA_Update`, ×100 — та сама ціла арифметика (переповнення u32 там немає за побудовою).
    def step_x100(prev_x100, raw_s)
      ((ALPHA_NUM * raw_s * SCALE) + ((ALPHA_DEN - ALPHA_NUM) * prev_x100)) / ALPHA_DEN
    end

    # EMA на дроті, якої вимагає рекурентність, — діапазон цілих секунд або nil, коли висновку немає.
    # Входи — цілі з дроту: кадр без EMA (паніка) розпакувальник у пару не бере, а сирий CCM-кадру є завжди.
    def expected_range(prev_ema:, raw:)
      return nil if prev_ema == unknown || prev_ema >= WIRE_MAX
      return nil if raw >= WIRE_MAX
      return prev_ema..prev_ema if raw == unknown # невимір фільтр пропускає (`EMA_Feed`)

      # Клемпу до WIRE_MAX тут немає свідомо: з несатурованими входами крок не сягає 0xFFFF
      # ((2·65 534·100 + 8·(65 534·100 + 99)) / 10 = 6 553 479 < 6 553 500).
      (step_x100(prev_ema * SCALE, raw) / SCALE)..(step_x100((prev_ema * SCALE) + SCALE - 1, raw) / SCALE)
    end

    # Відхилення EMA кадру від рекурентності, секунди: 0 — узгоджено; мінус — коротша за дозволену, тобто в
    # бік більших балів; nil — пару не судимо.
    def deviation(prev_ema:, raw:, ema:)
      return nil if ema == unknown

      range = expected_range(prev_ema: prev_ema, raw: raw)
      return nil unless range
      return 0 if range.cover?(ema)

      ema < range.begin ? ema - range.begin : ema - range.end
    end

    # Бік відхилення — мітка гістограми; саме значення пишеться модулем, бо від'ємні спостереження ламають
    # монотонність `_sum` (Prometheus читає її спад як скид лічильника).
    def side(deviation)
      if deviation.negative? then "short"
      elsif deviation.positive? then "long"
      else "exact"
      end
    end

    def unknown = SilkenNet::Attractor::DELTA_T_UNKNOWN_S
  end
end
