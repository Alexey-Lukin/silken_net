# Дім імен Turbo-стрімів — ОДИН, і кличуть його ОБИДВІ сторони тракту.
#
# 🔴 Чому це не косметика, а несуче. До цього кожне імʼя писалось руками з обох
# боків незалежно: 5 підписок (`app/views/components/**`) + 6 броадкастів
# (воркери/моделі/сервіси), плюс реєстр-коментар у `config/cable.yml` і таблиця
# в `04_04 §8.1`. Сторони не звіряло ніщо. Один символ різниці дає або тихо
# мертвий тракт, або — якщо втрачено саме токен `_org_` — живий крос-тенант витік
# (`00_07` SEC.25: `"telemetry_stream"` віддавав payload чужих Королев кожному
# автентифікованому глядачу).
#
# ⚠️ Чесно про доказову базу, бо перша редакція цього коментаря її ЗАВИЩУВАЛА.
# Розходжень самого ІМЕНІ СТРІМУ репо ще не відвантажувало — прецедентів нуль.
# Три відомі катастрофи цього роду (`wallet` проти `[wallet, :transactions]` ·
# `transaction_{id}` проти `blockchain_transaction_{id}` · `actuator_card_{id}`
# проти `actuator_{id}`) — це розходження **target-id і record-форми**, тобто
# СУСІДНЯ поверхня, якої цей дім не накриває взагалі. Отже виправдання не «так
# уже падало», а: (1) найбільший радіус ураження серед варіантів — втрата `_org_`
# дає ВИТІК, чого жодна з тих трьох дати не могла; (2) він зводить гейт-пару
# [UI.4] до звірки двох викликів однієї функції. Сусідня поверхня лишається
# відкритою (5 рукописних target-id у двох шарах) — трекається в `00_07` UI.4.
#
# 🔒 Що цей дім НЕ робить: він не доводить, що передана організація — глядачева.
# Render-time assert тут свідомо НЕ ставиться: він тавтологічний (усі три
# контролери виводять org тим самим виразом, з яким його б і порівнювали) і
# недосяжний для компонент-спек-харнеса, що рендерить через
# `ApplicationController.renderer`, де `current_user` не оголошений хелпером.
# ⚠️ Тут доти стояло, що це питання «живе в `subscribed` власного каналу — тобто
# у Ф1». Виміряно навпаки: клас каналу обирає КЛІЄНТ, а `reject` тихий і
# незворотний, тож субскрайб-авторизація калічить лише чесних. Ф1 шипнула
# ІДЕНТИЧНІСТЬ зʼєднання, а «чи МОЖЕ воно слухати» вирішує епоха в імені (Ф3,
# нижче) — «покинути адресу» замість «гейтити підписника». Деталь — `04_04 §8.1`.
#
# Форма дому вибрана так, щоб її читав AST-гейт (`lib/turbo_stream_inventory.rb`):
# клас імені видно з ІМЕНІ МЕТОДУ на цьому ресівері, тож `org`/`org_at` і
# `gateway_ota` лишаються РІЗНИМИ класами обовʼязку доказу, а не зливаються в
# «indirect». Додаючи сюди метод — додай його і в `BLESSED_KINDS`, інакше
# єдиний виклик, що адресує відкликане імʼя, стане для гейта непрозорим.
module TurboStreams
  module Name
    # Реєстр org-скоуплених стрімів. `fetch`, а не `[]`: описка в ключі мусить
    # падати гучно, а не народжувати тихе нове імʼя, на яке ніхто не підписаний.
    ORG_PREFIXES = {
      telemetry: "telemetry_stream",
      alerts: "ews_alerts",
      map: "geospatial_matrix",
      ledger: "blockchain_ledger",
      maintenance: "maintenance_records"
    }.freeze

    class << self
      # [SEC.25 Ф3] Імʼя несе ЕПОХУ організації, і саме вона робить відкликання
      # можливим: підпис детермінований і без TTL, тож єдиний спосіб знецінити
      # збережений токен — покинути адресу, на яку він указує.
      #
      # 🔴 `organization` МУСИТЬ бути обʼєктом, що несе і `id`, і `stream_epoch`
      # — голий `organization_id` тут більше не приймається, і це не суворість
      # заради суворості. Дім лишається ЧИСТОЮ функцією: якби він сам ходив по
      # епоху в БД за id, то мав би дві гілки резолву, які читають її в РІЗНІ
      # моменти (підписник — на початку запиту з уже завантаженого запису,
      # продюсер — у мить броадкасту), і пін «запис і id взаємозамінні» став би
      # істинним лише поза вікном ротації. Ціна свідома: три продюсери тепер
      # беруть `cluster.organization` замість `cluster.organization_id`, тобто
      # платять один індексований SELECT (per-job query-cache його з'їдає).
      def org(kind, organization)
        org_at(kind, demand_id(organization), demand_epoch(organization))
      end

      # Явна епоха — рівно для tombstone'а при ротації (`Organization#rotate_stream_epoch!`):
      # погасити треба ПОПЕРЕДНЮ адресу, а `org` за побудовою знає лише поточну.
      # ⚠️ Окремий вхід, а не необовʼязковий аргумент до `org`: довільна епоха в
      # загальному вході — це тихий розкол тракту (продюсер і підписник на різних
      # адресах), тобто рівно той клас, проти якого цей дім і зроблено. Викликач
      # рівно один, і він у `Organization`.
      def org_at(kind, organization_id, epoch)
        "#{ORG_PREFIXES.fetch(kind)}_org_#{organization_id}_e#{epoch}"
      end

      # Імʼя БЕЗ org-токена — безпечне лише транзитивно (сторінка, що його
      # рендерить, сама org-скоуплена). Тому в гейті це окремий клас із окремим
      # обовʼязком доказу, і форма того доказу залежить від кардинальності
      # сторінки, не від форми імені (стеля №4 у шапці scope-гейта).
      def gateway_ota(gateway)
        "ota_channel_#{demand_uid(gateway)}"
      end

      private

      # Fail-closed, і це НЕ захисне padding: `nil` тут дав би `..._org_` —
      # імʼя, СПІЛЬНЕ для всіх організацій, тобто рівно той витік, від якого цей
      # дім існує. Викликачі, що легально можуть не мати організації, гасять це
      # ВЛАСНИМ guard'ом (`return unless org_id` / `if @organization`) — тут
      # мовчазний фолбек був би гіршим за виняток.
      def demand_id(organization)
        id = organization.respond_to?(:id) ? organization.id : nil
        raise ArgumentError, "org-стрім без організації: імʼя стало б спільним для всіх" if id.blank?

        id
      end

      # Той самий fail-closed, що й для id, і з тієї ж причини: `nil` дав би
      # суфікс `_e` без числа — ОДНЕ імʼя на всі епохи, тобто адресу, яку
      # ротація не змогла б покинути. Гілка досяжна не лише через nil-колонку:
      # обʼєкт, завантажений із `select(:id)`, теж сюди прийде.
      def demand_epoch(organization)
        epoch = organization.respond_to?(:stream_epoch) ? organization.stream_epoch : nil
        raise ArgumentError, "org-стрім без епохи: імʼя стало б спільним для всіх поколінь" if epoch.blank?

        epoch
      end

      def demand_uid(gateway)
        uid = gateway.respond_to?(:uid) ? gateway.uid : gateway
        raise ArgumentError, "ota-стрім без uid шлюзу" if uid.blank?

        uid
      end
    end
  end
end
