# [DOC-T.99] Лічильник рухомої множини в прозі `00_07` — носій припису
# «Без волатильних лічильників» (`00_06 §3`).
#
# 🔴 ЧОМУ носій, а не переказ правила. Припис стоїть у каноні понад рік і не
# спрацював ЖОДНОГО разу: за одну сесію 2026-09-05 клас укусив шість разів, і
# кожен лічильник старів у бік, що ХОВАЄ роботу («пʼять» при шести, «десять»
# при одинадцяти, «чотири алерти» при пʼяти). Правило без носія не стріляє —
# і це рівно той клас, що описаний у `00_06 §3` над цим рядком.
#
# ⚖️ СУДИТЬ ФОРМУ, НЕ ІСТИНУ. Скрипт не знає, скільки ніг у пункту насправді,
# і знати не мусить: він питає, чи автор ВЗАГАЛІ вписав число рухомої множини
# в опис СТАНУ. Число може бути правдиве сьогодні — воно збреше завтра, і
# читач не матиме приводу перевірити. Тому лік автора один із двох:
#   • НАЗВАТИ членів замість лічити (іменована множина самоперевірна —
#     кожне імʼя грепається; лічильник ні), АБО
#   • лишити число з КОМАНДОЮ, що його відтворює — коли число несе сенс,
#     якого імена не несуть (запас під стелею, частка).
#
# 🔑 ДИСКРИМІНАТОР — «звіт про ПОДІЮ ⊥ опис СТАНУ», і він тут не евристика
# для зручності, а сама межа припису. Звіт датований і незмінний назавжди
# («розчеплено на 4 ноги (2026-07-16)»); опис стану мовчки старіє («лишились
# три ноги»). Тому рядок-сегмент, що несе ISO-дату або цитує історичну
# помилку в «лапках», НЕ прапорцюється — інакше гейт вимагав би брехати про
# незмінне, а такий гейт вчить себе гортати.
#
# Режими: advisory (за замовчуванням, exit 0) · `--strict` (exit 1 на хіті).
# ⛔ HARD лише ПІСЛЯ свіпу до нуля — гейт над множиною, що не зводиться,
# мертвий так само, як гейт над порожньою (`00_07` DOC-T.99).

require "set"

PATH = ARGV.find { |a| !a.start_with?("--") } || "docs/00_07_Action_Plan_Tracker.md"
STRICT = ARGV.include?("--strict")

# Числівники — цифри та українські слова. Межа зліва несе ДВІ відмови, обидві
# виміряні на живому корпусі: без `\p{L}` «багатогодинного» матчиться підрядком
# «один», а без КРАПКИ ідентифікатор `FW.2 гейт` читається як «2 гейт» —
# тобто гейт про лічильники прапорцював би посилання на пункт.
NUM = /(?<![\p{L}\d.])(?:\d{1,3}|один|одна|одне|одну|два|дві|три|чотири|п(?:ʼ|')?ять|шість|сім|вісім|дев(?:ʼ|')?ять|десять|одинадцять|дванадцять|обидв\p{L}+)(?![\p{L}])/i

# Іменники РУХОМИХ множин. Перелік і є частиною припису (`00_06 §3`): дрейф у
# трекері приходить не як «к-сть тестів», а як «три ноги» / «Три носії».
NOUN = /(?:ніг\p{L}*|ног[аиу]\b|чекбокс\p{L}*|правил\p{L}*|файл\p{L}*|сайт\p{L}*|гейт\p{L}*|пункт\p{L}*|алерт\p{L}*|носі\p{L}*|ланк\p{L}*|поверх\p{L}*|споживач\p{L}*|консюмер\p{L}*|воркер\p{L}*|спек\p{L}*)/i

COUNTER = /#{NUM}\s{0,3}(?:\*\*)?\s*#{NOUN}/

# Вікно, у якому шукаємо ознаку ЗВІТУ, — АСИМЕТРИЧНЕ, і це вимір, не смак:
# датований звіт відкриває свою клаузу («🔴 2026-09-02 canopy ЖИВИЙ: …»), тож
# дата стоїть НАЗАД від числа, а не навколо нього. Межу взято з корпусу
# 2026-09-05: у єдиного законного звіту дата за 140 символів назад, у
# найближчого СПРАВЖНЬОГО хіта — за 244. 180 лягає між ними з обох боків.
# 🔴 Стеля оголошена: пороги вивірені на вибірці з шести, тобто вони
# розділяють ВІДОМІ форми, а не доводять, що інших нема. Ширше вікно почне
# ковтати дату сусіднього твердження — тоді гейт мовчить із хибної підстави.
BACK_WINDOW = 180
FWD_WINDOW  = 90
ISO_DATE = /\d{4}-\d{2}-\d{2}/

# Форма ВИНЯТКУ — обовʼязкова частина гейта: без неї він вимагав би брехати
# про незмінне (`00_07` DOC-T.99). Три способи оголосити число незмінним, і
# всі три вже є природною мовою корпусу, тобто нікого не змушують до розмітки:
#   • ISO-дата у вікні — звіт про подію, заморожений назавжди;
#   • «лапки» — цитата історичної помилки або чужого твердження;
#   • слово «стал\*»/«вендорськ\*»/«design-факт» — автор ОГОЛОСИВ сталість.
DECLARED = /стал[аиео]|сталий|вендорськ|design-факт|незмінн/i

def reporting?(segment)
  segment.match?(ISO_DATE) || segment.include?("«") || segment.match?(/[Дд]оти/) ||
    segment.match?(DECLARED)
end

lines = File.readlines(PATH, chomp: true)
item = nil
hits = []

lines.each_with_index do |line, idx|
  if (m = line.match(/\A#### ([A-Z][A-Z0-9.\-]*)/))
    item = m[1]
    next
  end
  stan  = line.lstrip.start_with?("- **Стан:**")
  watch = line.include?("📊 WATCH")
  next unless stan || watch

  line.to_enum(:scan, COUNTER).each do
    md = Regexp.last_match
    seg = line[[ 0, md.begin(0) - BACK_WINDOW ].max...(md.end(0) + FWD_WINDOW)].to_s
    next if reporting?(seg)

    hits << { item: item, line: idx + 1, text: md[0], ctx: seg }
  end
end

if hits.empty?
  puts "✅ [DOC-T.99] волатильних лічильників стану в #{PATH} не знайдено"
  exit 0
end

puts "#{STRICT ? '❌' : '⚠️'} [DOC-T.99] лічильник рухомої множини в описі СТАНУ — #{hits.size} у #{hits.map { _1[:item] }.uniq.size} пунктах"
puts "   Лік: НАЗВАТИ членів замість лічити, або лишити число з командою, що його відтворює (`00_06 §3`)."
hits.each do |h|
  puts "\n  #{h[:item]} (рядок #{h[:line]}) — «#{h[:text]}»"
  puts "      …#{h[:ctx].gsub(/\s+/, ' ')}…"
end

exit(STRICT ? 1 : 0)
