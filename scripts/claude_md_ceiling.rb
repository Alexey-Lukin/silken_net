#
# scripts/claude_md_ceiling.rb — байтова стеля prepend-шару (`CLAUDE.md`).
#
# ЧОМУ. `CLAUDE.md` prepend-иться в КОЖЕН промпт, тож кожен його байт оплачується
# щоразу, а неправда в ньому читається ПЕРШОЮ. Критерій членства (шапка §6 файлу)
# тримала лише проза, а в прози немає червоного: файл уже раз наріс до 42.3 kB
# (зріз DOC-T.104 — до 30.8), і 2026-09-19 його знову різали, 30.9 → 24.8 kB.
# Стеля робить ДОДАВАННЯ дорогим: новий рядок мусить щось витіснити
# (⚖️ founder 2026-09-19 — «непотрібне — важким, важке — непотрібним»).
#
# ⚠️ ОГОЛОШЕНА СТЕЛЯ ГЕЙТА: міряє БАЙТИ, ніколи ПРАВДУ. Короткий хибний рядок пройде
# зеленим — проти неправди стоїть лише свіп (`00_05 §4`). Байти, а не символи: кирилиця
# важить 2 B на символ, і саме байти (≈ токени) є ціною prepend-у.
# ⛔ Стелю НЕ піднімають, щоб вмістити додавання: спершу виселяй — у скіл, канон чи
# памʼять — за критерієм §6. Підняти її можна лише окремим присудом founder-а з
# названою ціною, і тим самим комітом, що змінює цю константу.

CEILING = 26_000
path = File.expand_path("../CLAUDE.md", __dir__)
size = File.size(path)

if size > CEILING
  warn "claude_md_ceiling ✗ — CLAUDE.md = #{size} B > стелі #{CEILING} B (понад на #{size - CEILING} B)."
  warn "  Виселяй за критерієм §6 CLAUDE.md (стріляє ДО розпізнання домену?) у скіл/канон/памʼять;"
  warn "  стелю не піднімай, щоб вмістити додавання — лише присудом founder-а (шапка цього скрипта)."
  exit 1
end

puts "claude_md_ceiling ✓ — CLAUDE.md = #{size} B ≤ #{CEILING} B (запас #{CEILING - size} B)"
