# [SEC.25] Відв'язати ключ підпису Turbo-стрімів від `secret_key_base`.
#
# 🔴 Навіщо. Підписане ім'я стріму — детермінований `MessageVerifier` без TTL і
# без `purpose`, тобто **безстроковий capability-токен**: хто його бачив, той може
# підписатись і завтра. Епоха організації (`Organization#stream_epoch`, Ф3) відкликає
# лише ТРИ імені з семи; чотири record-form адреси лишаються безстроковими, і по
# одній із них — `[wallet, :transactions]` — течуть суми SCC, tx-хеші та статуси.
#
# Доти єдиним важелем на них вважалась ротація `secret_key_base` — а вона вилогінює
# геть усіх, ламає CSRF, `api_access`-токени й ActiveStorage-URL, тобто дорога рівно
# там, де не допомагає. Але turbo-rails підписує імена ВЛАСНИМ ключем і деривує його
# з `secret_key_base` лише ЗА ЗАМОВЧУВАННЯМ:
#
#   Turbo.signed_stream_verifier_key = config.turbo.signed_stream_verifier_key ||
#     Rails.application.key_generator.generate_key("turbo/signed_stream_verifier_key")
#
# Задавши його явно, ми дістаємо stream-only важіль: ротація ОДНОГО секрета знецінює
# кожне видане ім'я, не чіпаючи ані сесій, ані токенів, ані підписаних URL.
#
# 🔒 Три чесні стелі, інакше «важіль є» прочитається ширше, ніж воно є:
#   (1) він ГЛОБАЛЬНИЙ по організаціях — тупіший за епоху, яка б'є одну; це важіль
#       «злили щось, і ми не знаємо що», а не заміна епосі;
#   (2) ротація не рве вже відкритий сокет (верифікатор читають один раз у
#       `subscribed`) і лишає чесним глядачам ту саму тиху глухоту до наступної
#       навігації, якої tombstone post-hoc не лікує — їх уже відреджектило;
#   (3) 🔴 **ротація діє лише з РЕСТАРТОМ процесів** — `Turbo.signed_stream_verifier`
#       мемоїзований (`@signed_stream_verifier ||=`), тож зміна самого ключа в живому
#       процесі не робить НІЧОГО. Виміряно, а не виведено: підміна ключа в рантаймі
#       лишала старе ім'я валідним, і лише окремий процес із новим секретом дав `nil`.
#       Отже це деплой-час важіль, і в рецепті він мусить стояти як «оновити секрет
#       + прокотити рестарт», ніколи як «виконати в консолі».
# Механіка й порівняння з альтернативою (епоха в record-стрімі) — `04_04 §8.1`,
# ops-рецепт ротації — `06_04 §5.9`.
#
# ⚠️ Свідомо БЕЗ boot-guard'а: за відсутності ENV гем деривує ключ як і раніше, тож
# поведінка не змінюється — на відміну від AR-encryption ключів, без яких дані просто
# нечитабельні (`active_record_encryption_keys_check.rb` — інша мета, не копіювати
# форму сюди). Ціна такого вибору названа: секрет, який забули завести в проді, дає
# не падіння, а мовчазну відсутність важеля. Тому він стоїть у `06_04` як обов'язковий
# deploy-secret, і саме там його місце — не в коді.
Rails.application.config.turbo.signed_stream_verifier_key = ENV["TURBO_SIGNED_STREAM_KEY"].presence
