# [ARCH.103] Знімає схемний `DEFAULT 0.0` з `naas_contracts.emitted_tokens`.
#
# Колонка не має ЖОДНОГО писача — ні в застосунку, ні в сідах, ні у фабриках, —
# але завдяки дефолту кожен читач діставав упевнений `0`, невідрізнимий від
# чесного «ще не намінчено». Сім поверхонь друкували цей нуль як факт про гроші,
# включно з доларовою оцінкою портфеля (`sum(:emitted_tokens) * current_price`).
#
# 🔴 Підстава — НЕ «нуль писачів» (продакшну не було, тож це вимір недобудованості,
# а не смерті), а те, що величина **не має визначення**: кластер може нести кілька
# контрактів ОДНОЧАСНО (перетин періодів не заборонений жодною валідацією), а
# mint-рядок не має посилання на контракт узагалі — його має лише burn
# (`sourceable: NaasContract`). Тобто ні писач, ні деривація не знали б, якому з
# N контрактів приписати мінт. Присуд про семантику — `00_07` ARCH.103.
#
# Після цього `NULL` означає рівно те, що є: не виміряно. Коли семантику ухвалять,
# писач ставитиме справжнє число, і `0` знову стане законним ВИМІРОМ («намінчено
# нуль»), відрізнимим від порожнечі — саме те розрізнення, якого дефолт не давав.
