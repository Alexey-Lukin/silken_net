# [HW.9] RX-ланка SX126x (L5 · C11 · C12) — обчислювальний дім стартових номіналів
# поз. 19 (`02_01 §3.1`). Канон друкує РЕЗУЛЬТАТ і посилається сюди; формули й
# правило округлення живуть тут, бо число в прозі не має чим себе перевиміряти.
#
# Pure Ruby (no Rails / no bundle). Виклик:
#   ruby tools/firmware/rx_lna_match.rb           # шість кроків AN5457 для нашого корпусу й частоти
#   ruby tools/firmware/rx_lna_match.rb --assert  # позитивний контроль: опрацьований приклад ST
#
# 🔑 ЧОМУ ФАЙЛ САМОВАЛІДНИЙ. Методика — ST AN5457 Rev 3 (2022-12) §5.2, кроки 1–6;
# топологія — з самих рис. 62/66/67 (текстовий шар PDF несе підписи, не зʼєднання):
# вхід → послідовний C11 → RFI_P; L5 між RFI_P і RFI_N; C12 від RFI_N на землю.
# Доказ, що формули переписано правильно, — не цитата, а арифметика: `--assert`
# проганяє опрацьований приклад ST (UFBGA73, 915 МГц, Z_opt 62 + j112 Ω) і вимагає
# збігу з надрукованим (25.45 · 22.21 · 11.86 нГн · 1.68 · 2.7 · 4.45 пФ) і з вибором
# табл. 4 для L5 і C12 (12 нГн · 2R7). Зміни формулу — приклад розійдеться.
#
# ⚠️ Крок 6 рахує C11 ВІД НОМІНАЛУ C12, не від розрахункового: ST сама ставить 2.7
# (розраховано 2.725), і лише з номіналом виходить її 4.45; з розрахунковим вийшло б
# 4.38. Порядок вибору — C12 → C11, і скрипт робить так само.
#
# ⛔ СТЕЛІ, ОГОЛОШЕНІ ВГОЛОС — інакше зелений прогін почне означати «узгоджено»:
#   • Лумпова модель без паразитів плати й без Q деталей. ST сама показує, що на платі
#     номінали сідають НИЖЧЕ розрахованих (рис. 68: L5 11.86 → 11 нГн, C11 4.45 → 3.6 пФ),
#     тож це стартова точка першої партії; суддя — вимір на НАШІЙ платі
#     (`[bench:radio-phy]`, `firmware/scripts/bench/RUNBOOK.md` §6).
#   • Z_opt — табл. 17 AN: source-pull ST за RSSI і NF на пінах корпусу; ні нашої
#     плати, ні нашої оснастки він не бачив. Канал 868.x МГц проти рядка 868 —
#     Δf/f ≤ 0.03 %, нижче за крок будь-якого номіналу.
#   • Ланка «balun-подібна»: ST попереджає про фазовий дисбаланс RFI_P/RFI_N, що
#     залежить від реального R_LNA (рис. 63–65); модель його не рахує. Z_in нижче —
#     для навантаження Z_opt*, тобто про узгодження, не про баланс.
#   • Округлення — до найближчого (C — крок 0.1 пФ, L від 10 нГн — 1 нГн), як ST
#     обирає L5 і C12 у табл. 4. ⚠️ C11 там 4R5 при точних 4.447 — ST округлила вже
#     НАДРУКОВАНІ 4.45, тобто двічі; наші номінали від цього не залежать (4.917 → 4.9
#     за будь-якого з двох правил), тож `--assert` C11-вибору ST не пінить. Існування
#     саме цих номіналів у родинах GJM1555C/LQW15AN каталогом Murata НЕ звірено
#     (сайт віддає машині заглушку без даних), P/N обирається при KiCad BOM (`00_07` HW.9).
#   • Не в CI свідомо: номінали стартові й підлаштовуються на стенді, а `--assert`
#     стереже ТРАНСКРИПЦІЮ формул ST, не канон.

R0 = 50.0

# AN5457 Rev 3, табл. 17 — оптимальний ДИФЕРЕНЦІЙНИЙ імпеданс LNA на пінах, Z_opt = R + jX (Ω).
Z_OPT = {
  [ "UFQFPN48", 868 ] => [ 52.0, 102.0 ],
  [ "UFQFPN48", 915 ] => [ 60.0, 100.0 ],
  [ "UFBGA73", 868 ] => [ 52.0, 104.0 ],
  [ "UFBGA73", 915 ] => [ 62.0, 112.0 ]
}.freeze

# Наш випадок — дзеркала, правити в домі: корпус STM32WLE5CC → `02_01 §3.1` поз. 1;
# смуга 868 → `03_05 §2.1`.
OURS = [ "UFQFPN48", 868 ].freeze
ST_EXAMPLE = [ "UFBGA73", 915 ].freeze

# AN5457 §5.2: Z_LNA = Z_opt*, тобто Y = 1/(R − jX) = G + jB.
def rx_match(r, x, f_mhz)
  w = 2 * Math::PI * f_mhz * 1e6
  d = r**2 + x**2
  g = r / d
  b = x / d
  l5a = 1 / (w * b)                                   # крок 1: компенсувати ємність LNA
  bp = Math.sqrt(g / R0 - g**2)                       # крок 2: вийти на коло 50 Ω
  lp = 1 / (w * bp)
  ctot = 1 / (w * R0 * Math.sqrt((d / r) / R0 - 1))   # крок 4: послідовна C до центру
  c12 = 2 * bp / w                                    # крок 5: X_C12 = X_L′ / 2
  { w: w, l5a: l5a, lp: lp, l5: l5a * lp / (l5a + lp), ctot: ctot, c12: c12 } # крок 3: L5 = L5′ ∥ L′
end

# Крок 6: C11 ⊕ C12 = C_tot — від НОМІНАЛУ C12.
def c11_for(ctot, c12) = 1 / (1 / ctot - 1 / c12)

def round_c_pf(farad) = (farad * 1e12).round(1)
def round_l_nh(henry) = henry * 1e9 >= 10 ? (henry * 1e9).round : (henry * 1e9).round(1)

def nominals(m)
  c12 = round_c_pf(m[:c12])
  { l5: round_l_nh(m[:l5]), c12: c12, c11: round_c_pf(c11_for(m[:ctot], c12 * 1e-12)) }
end

# Вхідний імпеданс з боку 50 Ω при навантаженні Z_opt*: C11 ⊕ C12 послідовно + (L5 ∥ Z_LNA).
def z_in(r, x, w, n)
  zl = Complex(r, -x)
  zl5 = Complex(0, w * n[:l5] * 1e-9)
  cs = 1 / (1 / (n[:c11] * 1e-12) + 1 / (n[:c12] * 1e-12))
  zl5 * zl / (zl5 + zl) + Complex(0, -1 / (w * cs))
end

def return_loss_db(z) = -20 * Math.log10(((z - R0) / (z + R0)).abs)

def report
  r, x = Z_OPT.fetch(OURS)
  m = rx_match(r, x, OURS[1])
  n = nominals(m)
  z = z_in(r, x, m[:w], n)
  puts "RX-ланка AN5457 §5.2 — #{OURS[0]} @ #{OURS[1]} МГц, Z_opt = #{r} + j#{x} Ω (табл. 17)"
  puts format("  крок 1  L5′ = %.2f нГн   крок 2  L′ = %.2f нГн   крок 3  L5 = %.2f нГн", m[:l5a] * 1e9, m[:lp] * 1e9, m[:l5] * 1e9)
  puts format("  крок 4  C_tot = %.3f пФ   крок 5  C12 = %.3f пФ   крок 6  C11 = %.3f пФ (від номіналу C12)",
              m[:ctot] * 1e12, m[:c12] * 1e12, c11_for(m[:ctot], n[:c12] * 1e-12) * 1e12)
  puts "  номінали 0402 (правило табл. 4 AN): L5 #{n[:l5]} нГн · C11 #{n[:c11]} пФ · C12 #{n[:c12]} пФ"
  puts format("  ціна округлення: Z_in = %.1f %+.1fj Ω, зворотні втрати %.1f дБ (лумпова модель, без паразитів)",
              z.real, z.imag, return_loss_db(z))
  puts "  ⊕ AN рис. 67: опційний C13 0.7–1.2 пФ шунтом перед ключем — DNP-пад, якщо ключ пропускає гармоніки"
end

def near?(value, target, tol) = (value - target).abs < tol

def assert_mode
  m = rx_match(*Z_OPT.fetch(ST_EXAMPLE), ST_EXAMPLE[1])
  n = nominals(m)
  r, x = Z_OPT.fetch(OURS)
  ours = rx_match(r, x, OURS[1])
  checks = {
    "ST: L5′ 25.45 нГн" => near?(m[:l5a] * 1e9, 25.45, 0.01),
    "ST: L′ 22.21 нГн" => near?(m[:lp] * 1e9, 22.21, 0.01),
    "ST: L5 11.86 нГн" => near?(m[:l5] * 1e9, 11.86, 0.01),
    "ST: C_tot 1.68 пФ" => near?(m[:ctot] * 1e12, 1.68, 0.005),
    "ST: C11 4.45 пФ від номіналу C12 2.7" => near?(c11_for(m[:ctot], 2.7e-12) * 1e12, 4.45, 0.005),
    "ST табл. 4: L5 12 нГн · C12 2R7" => n[:l5] == 12 && near?(n[:c12], 2.7, 1e-9),
    "наш Z_in із номіналами: RL ≥ 20 дБ" => return_loss_db(z_in(r, x, ours[:w], nominals(ours))) >= 20
  }
  checks.each { |name, ok| puts "#{ok ? 'OK  ' : 'FAIL'} #{name}" }
  exit(checks.values.all? ? 0 : 1)
end

case ARGV.first
when nil then report
when "--assert" then assert_mode
else
  warn "невідомий режим #{ARGV.first.inspect}; доступні: (порожньо) · --assert"
  exit 2
end
