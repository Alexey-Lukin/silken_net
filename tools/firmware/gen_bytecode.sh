#!/usr/bin/env bash
# SPDX-License-Identifier: AGPL-3.0-or-later
# tools/firmware/gen_bytecode.sh — [FW.46 · FW.66 S4] regenerate the committed mruby
# bytecode mirrors of BOTH on-device contracts:
#   firmware/common/lorenz_bytecode.h — ECB era: metabolic_core.rb + bio_contract.rb
#   firmware/common/ccm_bytecode.h    — CCM era: metabolic_core.rb + ccm_contract.rb
# The metabolic formula lives ONCE (metabolic_core.rb) and mrbc compiles it into each
# contract, so the two eras cannot carry two drifting copies of the money formula.
#
# Builds the host mruby (if mrbc is absent) and runs `mrbc -B <symbol> <sources…>`,
# wrapping the output with an include guard, the source list and a sha256 stamp of
# the CONCATENATED sources — so the LIGHT stdlib gate (check_bytecode.py) can detect
# source-vs-mirror drift without needing mrbc (it reads the source list from the stamp).
#
#   tools/firmware/gen_bytecode.sh           # regenerate in place
#   tools/firmware/gen_bytecode.sh --check   # fail if regen != committed (CI)
#
# Determinism: mruby is pinned (firmware/extern/mruby submodule), the sources are
# passed as stable repo-relative paths, and RITE bytecode is endian-stable, so
# regen is byte-reproducible across the dev box (arm64) and CI (x86).
set -euo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
MRUBY="$REPO/firmware/extern/mruby"
MRBC="$MRUBY/build/host/bin/mrbc"
MRUBY_VER="4.0.0"
BC="firmware/bio_contracts"

# symbol | include guard | output | sources (space-separated, compile order)
TARGETS=(
  "lorenz_bytecode|SILKEN_LORENZ_BYTECODE_H|firmware/common/lorenz_bytecode.h|$BC/metabolic_core.rb $BC/bio_contract.rb"
  "ccm_bytecode|SILKEN_CCM_BYTECODE_H|firmware/common/ccm_bytecode.h|$BC/metabolic_core.rb $BC/ccm_contract.rb"
)

check=0
[ "${1:-}" = "--check" ] && check=1

if [ ! -x "$MRBC" ]; then
  echo "[FW.46] host mruby/mrbc absent — building…"
  ( cd "$MRUBY" && MRUBY_CONFIG="$REPO/firmware/mruby/build_config.rb" rake -j4 >/dev/null )
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
rc=0

for target in "${TARGETS[@]}"; do
  IFS='|' read -r sym guard out_rel srcs <<< "$target"
  read -r -a src_list <<< "$srcs"
  sha="$(cd "$REPO" && cat "${src_list[@]}" | shasum -a 256 | awk '{print $1}')"

  # mrbc emits `const uint8_t <sym>[] = {…};` (no debug info without -g).
  ( cd "$REPO" && "$MRBC" -B "$sym" -o "$tmp/$sym.body.h" "${src_list[@]}" )

  {
    # [UNI.3] SPDX emitted by the generator, not by the header sweep: --check does a full
    # `diff` against the committed file, so a tag added afterwards would read as drift.
    echo "// SPDX-License-Identifier: AGPL-3.0-or-later"
    echo "/* GENERATED by tools/firmware/gen_bytecode.sh — DO NOT EDIT BY HAND."
    echo " *"
    echo " * Sources:   ${srcs}"
    echo " * mruby:     ${MRUBY_VER} (firmware/extern/mruby submodule)"
    echo " * float:     double (NO MRB_USE_FLOAT — FW.19 / FW.7 byte-parity)"
    echo " * sources sha256: ${sha}"
    echo " *"
    echo " * Regenerate: tools/firmware/gen_bytecode.sh"
    echo " * Drift-gate: tools/firmware/check_bytecode.py (light, stdlib)"
    echo " *             tools/firmware/gen_bytecode.sh --check (deep, needs mrbc)"
    echo " */"
    echo "#ifndef ${guard}"
    echo "#define ${guard}"
    echo ""
    cat "$tmp/$sym.body.h"   # mrbc -B already emits: #include <stdint.h> + const uint8_t …
    echo ""
    echo "#endif /* ${guard} */"
  } > "$tmp/$sym.h"

  if [ "$check" = 1 ]; then
    if ! diff -q "$tmp/$sym.h" "$REPO/$out_rel" >/dev/null 2>&1; then
      echo "❌ [FW.46] $out_rel is stale vs ${srcs} — regenerate:"
      echo "   tools/firmware/gen_bytecode.sh"
      diff "$REPO/$out_rel" "$tmp/$sym.h" || true
      rc=1
    else
      echo "✅ [FW.46] $out_rel matches ${srcs}"
    fi
  else
    cp "$tmp/$sym.h" "$REPO/$out_rel"
    # Розмір RITE-байткоду — вхід стель OTA Солдата (FW.67); гейт — диспетчер і його пін, тут лише показ.
    size="$(grep -o '0x[0-9a-fA-F][0-9a-fA-F]' "$tmp/$sym.body.h" | wc -l | tr -d ' ')"
    echo "✅ [FW.46] wrote $out_rel (${size} B bytecode · sources sha256 ${sha})"
  fi
done

exit "$rc"
