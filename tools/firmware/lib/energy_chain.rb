# [ARCH.8] Спільний енергетичний ланцюг вузла — ОДИН дім арифметики, яку доти
# несли ДВА прилади порізно: `tx_cadence_budget.rb` (річна каденція, питання
# ARCH.8) і `boot_brownout_cycle.rb` (зимове гістерезисне вікно, питання HW.44).
#
# ⛔ ЧОМУ ЦЕ БІБЛІОТЕКА, А НЕ ЗЛИТТЯ ПРИЛАДІВ. Два файли ставлять РІЗНІ питання
# й мають різні стелі: перший про баланс на роках, другий про виживання трьох
# warmup-циклів на одному заряді. Спільні в них не питання й не висновки, а
# рівно чотири формули нижче — сон-стік VSTOR, годинний перерахунок, годинна
# генерація й ціна активного циклу з VSTOR. Зливати прилади було б помилкою
# (реєстр `00_06 §3`, рядок TX-cadence budget: прилади свідомо не злиті); дублювати формули — теж, бо третя
# копія вже стукала у двері.
#
# ⛔ ФУНКЦІЇ БЕРУТЬ ІМЕНОВАНІ АРГУМЕНТИ, А НЕ ХЕШ ПАРАМЕТРІВ. Обидва прилади
# мають власні `PARAMS` із власними ключами (напр. `eta_boost` ⊥
# `eta_boost_winter` — зимова точка 0.65 проти річної 0.68), і хеш-інтерфейс
# мовчки взяв би чужий ККД, щойно ключі розійдуться. Іменований аргумент
# змушує кожного викличника НАЗВАТИ, який саме ККД він подає.
#
# ⛔ ОГОЛОШЕНА СТЕЛЯ: тут немає ЖОДНОГО канон-числа. Значення живуть у
# `PARAMS` приладів, а їхня відповідність надрукованому в `02_03` доводиться
# `--assert`-ами ТАМ, не тут. Ця бібліотека не має власного гейта за
# побудовою — її стереже те, що обидва асерти читають її вихід.
module SilkenEnergyChain
  module_function

  # Сон-стік із VSTOR (µW): buck-гілка (STM32 у STOP2, через ККД idle-buck)
  # плюс ПРЯМА квієсцентна гілка BQ25570, що живиться з VSTOR без buck'а.
  # Відтворює 02_03 §9.3 крок-у-крок.
  def sleep_drain_uw(i_stm32_sleep_na:, v_out:, eta_buck_sleep:, i_bq_quiescent_na:, v_vstor_avg:)
    p_stm32_sleep_uw = (i_stm32_sleep_na / 1000.0) * v_out
    p_drawn_from_vstor_uw = p_stm32_sleep_uw / eta_buck_sleep
    p_bq_q_uw = (i_bq_quiescent_na / 1000.0) * v_vstor_avg
    p_drawn_from_vstor_uw + p_bq_q_uw
  end

  # µW → мДж/год. Тривіально, але живе тут, щоб множник 3600/1000 стояв в
  # одному місці: саме він двічі переписувався в обох приладах.
  def mj_per_hour(uw) = uw * 3600.0 / 1000.0

  # Годинна генерація з VSTOR (мДж/год) — ККД boost'а подає ВИКЛИЧНИК, бо
  # зимова й річна точки різні (див. шапку).
  def gen_mj_per_hour(p_gen_uw:, eta_boost:) = mj_per_hour(p_gen_uw * eta_boost)

  # Ціна одного активного циклу, знята з VSTOR (мДж): корисне навантаження
  # ділиться на ККД active-buck'а. `tx_mj` подає викличник, бо він у двох
  # приладів різного походження — один рахує його з airtime, другий бере
  # фіксовану season-independent цифру §9.4/§9.6.
  # ⛔ `rx_mj` і `tcxo_mj` ОБОВʼЯЗКОВІ й іменовані, а не дефолтні нулі: пост-TX RX-вікно
  # прошивка відкриває ЩОЦИКЛУ (ворота `VCAP_LISTEN_THRESHOLD` вироджені), а TCXO живий,
  # поки живе радіо, — і саме ці два члени бюджет доти мовчки не ніс (ARCH.8, 2026-09-26).
  # Дефолт 0 повернув би ту саму тиху відсутність, тож викличник мусить назвати число.
  def active_cycle_from_vstor_mj(tinyml_mj:, lorenz_mj:, tx_mj:, rx_mj:, tcxo_mj:, eta_buck_active:)
    (tinyml_mj + lorenz_mj + tx_mj + rx_mj + tcxo_mj) / eta_buck_active
  end
end
