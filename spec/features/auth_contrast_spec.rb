require "rails_helper"
require Rails.root.join("spec/support/contrast_registry")

# [UI.3] Родина `AuthLayout` тримає AA в ОБОХ темах — на сторінках, які бачить
# кожен вхід і кожне відновлення пароля.
#
# 🔴 Чому це окремий файл, а не чотири рядки в `contrast_root_tokens_spec`:
# весь той контур стоїть за `before { sign_in_as }`, а ці сторінки живуть ДО
# автентифікації. Доти вони були поза контуром за ПІДСТАВОЮ, яка померла:
# `AuthLayout` хардкодив `dark`, тобто світлої теми ці екрани не мали взагалі.
# Хардкод знято 2026-08-08 разом із тумблером (UI.1), і виняток пережив свою
# підставу на десять днів.
#
# 🔬 ЩО ЦЕЙ ФАЙЛ КУПИВ — і чому лантерни нижче несучі, а не церемонія.
# Головна дія сторінки входу (`AUTHENTICATE`) провалювала AA у світлій темі
# (**2.28:1** при барі 4.5) і була невидима ОБОМ приладам одразу, двома
# НЕЗАЛЕЖНИМИ сліпотами, що лягли на один вузол:
#   · текст кнопки живе в атрибуті `value`, тож обхідник текстових вузлів не
#     бачив його за побудовою — вузол не потрапляв навіть у кошик «невимірне»;
#   · картка несе `backdrop-blur-xl`, тож збирач обривав обхід фону як
#     `painted_backdrop` — тобто ВЕСЬ вміст картки був «відмовою міряти».
# Обидві зняті в `spec/support/contrast_audit.rb` (там же — межі кожної).
# Тому лантерни пінять не «пари є», а що ЖИВИЙ саме той прохід, який ховав
# дефект: без них зелений колір тут означав би рівно те, що означав раніше.
#
# 🔒 Стелі (чесно й поіменно):
#   · три сторінки родини, а не «всі публічні»; ✅ але перелік більше не
#     літерал тут — він приходить із `ContrastRegistry::CONTOURS[:auth]`,
#     а популяцію стереже `spec/quality/contrast_contour_registry_spec.rb`
#     (`00_07` UI.3);
#   · один розмір вікна (1440×900) — мобільна розмітка має власну;
#   · СТАНИ (`:hover`/`:focus-visible`/`::placeholder`) не покриті: статичний
#     знімок їх не має, і `placeholder` є псевдоелементом із власним кольором;
#   · судиться ТЕКСТ, не рамки: `border-gaia-primary` на тих самих кнопках дає
#     ~2.3:1 у світлій проти бару 3:1 (1.4.11, non-text) — вимір є, присуду
#     нема, тож пункт лишається відкритим у `00_07` UI.3, а не мовчить тут;
#   · пара, розвʼязана крізь blur, доказова доти, доки позаду неї стоять лише
#     ПРЕДКИ: абсолютний оверлей за карткою прилад не бачить (та сама z-index
#     стеля, що оголошена в збирачі).
#
# ⚠️ Перед прогоном переконайся, що `public/assets/` НЕМАЄ — залишковий манифест
# тримає Propshaft на Static-резолвері й віддає застарілий CSS (стеля 3а в
# `spec/support/feature_helper.rb`).
RSpec.describe "[UI.3] AuthLayout тримає AA в обох темах", :js do
  let(:password) { "auth-contrast-pass-1" }
  let!(:user) { create(:user, password: password) }

  # ⚠️ `/reset_password` вимагає параметра, і саме він виявив, що прилад не вмів
  # відвідати жодну таку сторінку: `have_current_path(..., ignore_query: true)`
  # зрізає query у ФАКТИЧНОГО шляху й не зрізає в очікуваного. Звідси
  # `expect_path:` у збирачі — тут воно виводиться само.
  def auth_pages
    ContrastRegistry.paths_for(:auth, reset_token: user.generate_token_for(:password_reset))
  end

  %i[dark light].each do |theme|
    it "тема #{theme}: жодна пара auth-родини не провалює свій поріг" do
      harvests = auth_pages.map { |path| harvest_contrast(path, theme: theme) }
      pairs = harvests.flat_map { _1[:pairs] }

      expect(pairs).not_to be_empty, "жодної пари — збирач зламаний, вимір недійсний"

      # 🔴 Лантерн №1: атрибутний прохід живий. Зніми його — і кнопка входу
      # знову зникне з обліку МОВЧКИ (не в «невимірне», а в нікуди), тобто
      # приклад стане зеленим саме на тому вузлі, заради якого написаний.
      # ⚠️ Підмет тут ОДИН, і це вимір, а не послаблення: `input[type=submit]`
      # у родині несе лише `/login`; `forgot`/`reset` шлють `<button>` зі
      # звичайним текстовим вузлом. Перша редакція піна вимагала «на кожній
      # сторінці» й падала на здоровому дереві. Якщо цей лічильник колись
      # ЗАКОНОМІРНО стане нулем (усі сабміти переїдуть на `<button>`), лантерн
      # утратив підмет — його треба ПЕРЕЦІЛИТИ, а не зняти.
      expect(pairs.count { _1.sample_path.to_s.end_with?("@value") }).to be >= 1,
                                                                        "підпис кнопки в атрибуті не виміряний — атрибутний прохід мертвий"

      # 🔴 Лантерн №2: резолюція крізь `backdrop-filter` жива. Без неї весь
      # вміст картки повертається в «невимірне», і приклад теж зеленіє —
      # цього разу на порожній множині вимірних пар усередині картки.
      expect(pairs.count(&:blurred)).to be >= auth_pages.size,
                                        "жодної пари крізь blur — вміст картки знову невимірний"

      # 🔴 Ратчет: auth-родина мусить лишатись ПОВНІСТЮ вимірною. Новий градієнт
      # чи фото під текстом тут — не косметика, а повернення сліпої зони, у якій
      # дефект уже одного разу прожив.
      refusals = harvests.flat_map { _1[:buckets]["unmeasurable"].to_a }
      expect(refusals).to be_empty, "прилад відмовився міряти: #{refusals.inspect}"

      failures = pairs.reject(&:passes).map do |p|
        format("%.2f (бар %.1f) — %s на %s [%s] «%s»",
               p.ratio, p.threshold, p.colour, p.backdrop, p.sample_path, p.sample_text)
      end
      expect(failures).to be_empty, "AA провалено:\n  #{failures.uniq.join("\n  ")}"
    end
  end
end
