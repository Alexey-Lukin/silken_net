require "rails_helper"

# Гейт класу «`%{count}` + іменник у ЗАСТИГЛІЙ формі».
#
# Англійська ховає цю помилку за одним `-s`, тож у базовій локалі рядок виглядає
# бездоганно: `"%{count} units"`. У відмінюваних мовах він ламається на кожному
# числі, де форма інша: «21 одиниць», «1 vienības», «10 vienetai».
#
# 🔴 Чому це не бачить ЖОДЕН наявний гейт — і не випадково: `i18n-tasks missing`
# міряє НАЯВНІСТЬ ключа, `check-consistent-interpolations` — набір змінних `%{}`,
# `check-normalized` — форму YAML. Граматичність форми не міряє ніхто, а
# `rails-i18n` дає лише ПРАВИЛА плюралізації — обирати між `few`/`many` він може
# тільки якщо ключ узагалі є plural-блоком. На ~1 600 ключів корпусу їх було три.
#
# Форма — курована tripwire з ДВОМА списками (`00_06 §3`), і різниця між ними
# несуча: `EXEMPT` — рядки, де узгоджувати нічого (число стоїть останнім, після
# нього іменника немає) — це назавжди; `PENDING` — реальний борг, і він мусить
# ТІЛЬКИ скорочуватись. Мертвий запис у будь-якому списку червонить (інакше
# «0 порушень» означало б «0 перевірок»).
#
# 🔒 Стеля: перевіряється лише БАЗОВА локаль (ціна не росте з каталогом) і лише
# наявність plural-блоку — правильність САМИХ форм у кожній мові гейт не судить.
# ⚠️ Набори форм, які обирає ПРАВИЛО: uk `[one few many other]` · lt
# `[one few other]` · lv `[one other]` · en `[one other]`. Для lv нуль дає
# `:other` (`RailsI18n::Pluralization::Latvian` — `n % 10 == 1 && n % 100 != 11
# → :one`, інакше `:other`).
#
# 🔴 **АЛЕ «правило не має категорії `zero`» ≠ «ключ `zero:` мертвий», і цей
# корпус двічі помилявся тут у ПРОТИЛЕЖНІ боки** (розвʼязано 2026-08-21,
# I18N.1, читанням джерела гема). `I18n::Backend::Pluralization#pluralize`
# (i18n 1.15.2) робить шорткат ПЕРЕД правилом:
#   `return entry[:zero] if count == 0 && entry.has_key?(:zero)`
# — і супроводжує його власним коментарем «Deprecation: The use of the `zero`
# key in this way is incorrect … We keep this incorrect behaviour for now for
# backwards compatibility until we can remove it» (ruby-i18n#629). Тобто
# `zero:` обирається СЬОГОДНІ, у будь-якій локалі, повз її правило —
# доказ у дереві живий: `config/locales/mailers/lv.yml` `expiry.zero` для 0
# («0 minūšu», що для латиської й правильно, бо правило дало б «0 minūtes»).
#
# 🔬 **Обидва попередні виміри були ПРАВДИВІ — про різні обʼєкти, і саме тому
# суперечили один одному.** Спостереження «zero працює» міряло РЕНДЕР блоку,
# що має `zero:`; висновок «lv не має zero» міряв ПРАВИЛО (і `i18n.plural.keys`,
# який теж не бачить шортката). Урок ширший за i18n: коли два записи про той
# самий предмет суперечать, спершу спитай, чи вони про той самий ОБʼЄКТ —
# і закривай питання ДЖЕРЕЛОМ, а не третім виміром із того ж боку.
#
# ⚖️ Підтримуваний наступник — явний CLDR-ключ `'0'` (той самий метод, рядки
# нижче: `entry[symbolic_count(count)]`). Ми на нього НЕ мігрували свідомо:
# `i18n-tasks 1.1.2` не знає `'0'` серед plural-суфіксів і вимагає його в
# КОЖНІЙ локалі каталогу, тобто ціна росте з каталогом. Тригер міграції —
# `i18n-tasks`, що навчиться `'0'`, або реальне зняття шортката з гема
# (`00_07` I18N.1).
RSpec.describe "pluralized strings declare a plural block" do # rubocop:disable RSpec/DescribeClass
  # Число — ЗНАЧЕННЯ після двокрапки, а не числівник при іменнику → узгоджувати
  # нема з чим у жодній мові.
  # 🔴 Критерій ПЕРЕПИСАНО 2026-08-21 (I18N.1, нативний пас), і замінилась саме
  # підстава, а не вердикт. Доти тут стояло «число останнє», а стеля чесно
  # називала критерій АНГЛОЦЕНТРИЧНИМ і роутила сумнів у трекер: мовляв, uk дає
  # «Живих активних вузлів: 1» з іменником, замороженим у родовому множини.
  # Вимір мовами показав, що замороження тут ЗАКОННЕ: це штатна українська
  # конструкція лічильника («Повідомлень: 1»), де іменник узгоджується з
  # неявною «кількістю», а не з числом; lv (`Aktīvie tiešraides mezgli:`) і lt
  # (`Aktyvūs tiesioginiai mazgai:`) так само беруть називний множини як НАЗВУ
  # категорії, а не як числівникову групу. Отже звільняє не ПОЗИЦІЯ числа, а
  # його РОЛЬ — підпис «категорія: значення» ⊥ числівникова група, — і цей
  # критерій мовно-нейтральний, тож більше не роздає дозволів мовам, яких він
  # не бачить. Усі три записи нижче проходять саме за ним.
  # ⚠️ [I18N.4] Коментар стоїть ТУТ, а не всередині `%w[]`: там `#` — звичайний
  # символ, тож слова коментаря стають ЕЛЕМЕНТАМИ (спіймано dead-entry-прикладом).
  # Останній запис: число стоїть у кінці рядка, після двокрапки — узгоджувати нема
  # з чим у жодній мові; перша версія («%{count} HEX-символів») ставила іменник
  # після числа, і цей гейт її законно завернув.
  let(:exempt) do
    %w[
      dashboard.map.live_nodes
      account_security.show.mfa.enabled_with_remaining
      activerecord.errors.models.bio_contract_firmware.attributes.bytecode_payload.exceeds_size_limit
    ]
  end

  # Борг ВИЧЕРПАНО 2026-08-21 (I18N.1, нативний пас): усі сім ключів дістали
  # plural-блоки в чотирьох локалях ОДНИМ комітом — робота атомарна за
  # побудовою, бо блок лише в базовій локалі валить `i18n-tasks missing`.
  # Список лишається порожнім і тільки таким: новий `%{count}`-рядок мусить
  # АБО нести блок, АБО довести, що число в ньому — значення після двокрапки
  # (критерій `exempt` вище). Повернути сюди ключ = свідомо завести борг.
  # ⚠️ Форми, які обирає правило, різні за мовами й НЕ виводяться з CLDR
  # напам'ять: uk `[one few many other]` · lt `[one few other]` · lv
  # `[one other]` · en `[one other]` — тож блок із `many:` для lt був би
  # мертвим ключем. ⊥ `zero:` виняток: він обирається шорткатом бекенда повз
  # правило (шапка вище), тож для локалі, якій нуль потрібен окремою формою,
  # це ЖИВИЙ інструмент — і водночас депрекований.
  let(:pending_keys) { [] }

  let(:plural_suffixes) { %w[zero one two few many other] }
  # YAML напряму, а не `I18n.backend` — його внутрішній кеш лінивий і на момент
  # прикладу може бути порожнім (KeyError). Джерело істини тут — самі файли.
  let(:base_values) do
    base = I18n.default_locale.to_s
    Dir[Rails.root.join("config/locales/**/#{base}.yml")].sort.each_with_object({}) do |path, acc|
      root = YAML.load_file(path)&.fetch(base, nil)
      flatten_locale(root, [], acc) if root.is_a?(Hash)
    end
  end
  # Ключ вважається плюралізованим, якщо його ЛИСТ — одна з CLDR-форм.
  let(:count_keys) do
    base_values.select { |k, v| v.is_a?(String) && v.include?("%{count}") }
               .keys
               .reject { |k| plural_suffixes.include?(k.split(".").last) }
  end

  def flatten_locale(hash, path = [], acc = {})
    hash.each do |k, v|
      v.is_a?(Hash) ? flatten_locale(v, path + [ k.to_s ], acc) : acc[(path + [ k.to_s ]).join(".")] = v
    end
    acc
  end



  it "is a live check (the base locale really carries %{count} strings)" do
    expect(base_values).not_to be_empty
    expect(count_keys).not_to be_empty,
      "жодного `%{count}`-рядка не знайдено — сканер дивиться не туди"
  end

  it "has no dead entry in either list" do
    dead = (exempt + pending_keys).reject { |k| count_keys.include?(k) }

    expect(dead).to be_empty,
      "запис списку більше не існує як плоский `%{count}`-ключ (мігрував або перейменований) — приберіть його: #{dead.join(', ')}"
  end

  it "flags every %{count} string that is neither exempt nor a known debt" do
    unknown = count_keys - exempt - pending_keys

    expect(unknown).to be_empty,
      "новий `%{count}`-рядок без plural-блоку — у відмінюваних мовах він зламається на 1/21/… : #{unknown.join(', ')}"
  end

  # 🔔 НОСІЙ ТРИГЕРА `00_07` I18N.1 — свідомо ПОЗА стелею файлу, і ціна цього нульова.
  #
  # Стеля вище («лише БАЗОВА локаль, щоб ціна не росла з каталогом») стосується
  # СКАНУВАННЯ корпусу. Цей приклад нічого не сканує: він пінить ОДИН відомий ключ
  # в ОДНІЙ мові, тож його вартість константна й від каталогу не залежить.
  #
  # Що він стереже: вся шапка цього файлу описує депрекований шорткат бекенда
  # (`return entry[:zero] if count == 0 && entry.has_key?(:zero)`) — і **описувала
  # його без жодного піна**. Тобто тригер міграції на явний CLDR-ключ `'0'` був
  # НАЗВАНИЙ, але не мав чим спрацювати: у день, коли гем зніме шорткат, латиська
  # тихо почала б віддавати нулю форму правила («0 minūtes» — граматично хибну),
  # і жоден приклад корпусу цього не бачив би. Мовчазна регресія в мові, носія якої
  # серед нас немає, — рівно той клас, що не має шансу спливти інакше.
  #
  # Форма піна: рівність РЕНДЕРУ з `zero`-листом, а не з текстовим літералом —
  # тоді редагування самого перекладу пін не зачіпає, а зміна МЕХАНІЗМУ вибору
  # форми валить його поіменно.
  #
  # Три `expect` — це три РІЗНІ світи, і кожен потребує власного повідомлення,
  # бо реакція на них протилежна:
  #   1. ключ зник із YAML         → хтось прибрав лік; латиський нуль зламано ЗАРАЗ;
  #   2. `zero:` == `other:`       → пін перестав розрізняти механізм (вічнозелений);
  #   3. рендер більше не бере `zero` → сталася подія-тригер, час мігрувати на `'0'`.
  # ⚠️ Без (1) мутація «прибрати ключ» падала `NoMethodError` на `nil.sub`, тобто
  # пін червонів НЕ на тому ассерті — саме та форма, яку `guard-craft` називає
  # мутацією, що не дістає ассерта.
  #
  # 🔒 Стеля цього приклада: мутувати САМ вибір гілки не можна без підміни гема,
  # тож (3) верифіковано непрямо — виміром, що `zero`-лист і `other`-лист
  # текстово різні (ліхтар 2) і що рендер нуля збігається саме з `zero`-листом.
  # У день зняття шортката бекенд поверне `other`-форму, і (3) почервоніє.
  it "still selects the deprecated `zero:` shortcut for lv (I18N.1 trigger carrier)" do
    key    = "password_mailer.reset_instructions.expiry"
    leaves = YAML.load_file(Rails.root.join("config/locales/mailers/lv.yml"))
                 .dig("lv", "password_mailer", "reset_instructions", "expiry")

    expect(leaves["zero"]).to be_present,
      "lv `expiry.zero` зник — латиський нуль повернувся до форми правила " \
      "(«0 minūtes» замість родового множини «0 minūšu»). Це не прибирання сміття"

    expect(leaves["zero"]).not_to eq(leaves["other"]),
      "`zero:` і `other:` збіглися — пін нижче перестав розрізняти механізм вибору форми"

    expect(I18n.t(key, count: 0, locale: :lv)).to eq(leaves["zero"].sub("%{count}", "0")),
      "бекенд більше не обирає `zero:` для нуля — шорткат знято гемом (ruby-i18n#629). " \
      "Час мігрувати lv на явний CLDR-ключ `'0'`: `00_07` I18N.1"
  end
end
