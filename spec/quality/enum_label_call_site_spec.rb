require "rails_helper"

# [I18N.1] Гейт на САЙТ РЕНДЕРУ, а не на парність міток. Дім правила — `04_04 §12`.
#
# 🔴 Чому окремий гейт, коли `enum_label_parity_spec` уже є. Той судить ІНШУ
# половину: чи мітка існує в усіх чотирьох локалях. Він зелений і тоді, коли
# мітка бездоганна, а вʼю її НЕ ПИТАЄ — тобто рівно в стані, з якого починався
# цей клас. Виміряно 2026-08-19: `User#role` має дім (`ROLE_LABEL_SCOPE`), мітки
# в 4 локалях і чотири правильні викликачі — а дві поверхні друкували сирий
# англійський токен, і одна з них ставила його поруч із ПЕРЕКЛАДЕНОЮ міткою
# (`meta_row(t(".metadata.role"), @user&.role.to_s.upcase)`).
#
# 🔴 І причина промаху варта окремого рядка, бо вона повторювана: коментар дому
# перелічував периметр ЧИСЛОМ («роль рендериться на ЧОТИРЬОХ поверхнях»). Число
# було правдиве в мить написання, тож наступні дві поверхні не мали де
# зʼявитись — лічильник не червоніє, коли світ його переростає.
#
# 🧱 ДЖЕРЕЛО ПЕРЕЛІКУ — самі моделі: гейт збирає `*_LABEL_SCOPE`-константи й
# деривує з них імʼя атрибута. Отже новий домашній скоуп потрапляє під нагляд
# автоматично, а рукописного списку, який міг би відстати, тут немає.
#
# 🔒 Стелі названо:
#   1. Судяться ДВІ форми, і обидві куплені хибними спрацюваннями першої
#      редакції: (а) атрибут із текстовим форматуванням одразу після нього
#      (`.to_s`/`.upcase`/…) — саме нею головний дефект і стояв, поза
#      Phlex-блоком; (б) атрибут як ГОЛИЙ вміст блоку `{ … }`, без `(` між
#      дужкою й ним. Диспетчеризація (`case x.attr`), порівняння, ключі хешів і
#      АРГУМЕНТ хелпера, що деривує сам (`action_badge(record.action_type)`),
#      не судяться. Рядкові літерали знімаються перед матчем — інакше i18n-ключ
#      `t(".actor.role")` читається як звертання до атрибута.
#   2. Гейт не знає, чи мітка ПРАВИЛЬНА — це робота `enum_label_parity_spec`.
#   3. Периметр — `app/views/**`. Значення, що тече в JSON-блупринт, судиться
#      іншим питанням (машинний споживач має право на сирий токен).
RSpec.describe "[I18N.1] Кожен сайт рендеру enum'а питає ДІМ мітки", type: :model do
  let(:models_dir) { Rails.root.join("app/models") }
  let(:view_files) { Dir.glob(Rails.root.join("app/views/**/*.rb")) }

  # `DEVICE_TYPE_LABEL_SCOPE` → `device_type`. Джерело — константи в моделях.
  let(:labelled_attributes) do
    Dir.glob(models_dir.join("**/*.rb")).flat_map { |p| File.read(p).scan(/(\w+)_LABEL_SCOPE\s*=/) }
       .flatten.map(&:downcase).uniq.sort
  end

  it "ліхтар: константи-скоупи знайдено (порожній перелік = вакуумний гейт)" do
    expect(labelled_attributes.size).to be >= 4,
                                        "знайдено #{labelled_attributes.size} `*_LABEL_SCOPE` — джерело переліку обвалилось"
  end

  it "ліхтар: у дереві є вʼю (порожній glob = вакуумний гейт)" do
    expect(view_files.size).to be >= 50, "знайдено #{view_files.size} вʼю — glob обвалився"
  end

  it "жодна вʼю не рендерить сирий атрибут, що має дім мітки" do
    offenders = labelled_attributes.flat_map do |attr|
      # `(?!_label)` несучий — інакше правильний виклик `x.role_label`
      # читається як порушення.
      # (а) атрибут, ФОРМАТОВАНИЙ як текст — `.to_s`/`.upcase`/… одразу після нього.
      #     Ловить `meta_row(t(".metadata.role"), @user&.role.to_s.upcase)`, тобто
      #     головний реальний дефект, який НЕ стоїть у Phlex-блоці й тому першою
      #     редакцією цього гейта не ловився зовсім.
      # (б) атрибут як ГОЛИЙ вміст блоку `{ … }` — без `(` між дужкою й ним, бо
      #     `{ action_badge(record.action_type) }` це АРГУМЕНТ хелпера, а хелпер
      #     деривує мітку сам (ратифікована форма); гейт, що червонів би на ньому,
      #     заборонив би правильну конструкцію.
      text_format = /\.#{Regexp.escape(attr)}\b(?!_label)\s*(?:&?\.\s*)?(?:to_s|upcase|capitalize|titleize|humanize)\b/
      bare_block  = /\{[^(){}]*\.#{Regexp.escape(attr)}\b(?!_label)[^(){}]*\}/
      shapes = [ text_format, bare_block ]

      view_files.flat_map do |path|
        File.readlines(path).each_with_index.filter_map do |line, i|
          next if line.lstrip.start_with?("#")

          # 🔴 Рядкові літерали ЗНІМАЮТЬСЯ першими: `t(".actor.role")` містить
          # `.role` всередині i18n-КЛЮЧА, і перша редакція читала його як
          # звертання до атрибута — два хибні червоні з трьох.
          code = line.gsub(/"[^"]*"/, '""').gsub(/'[^']*'/, "''")
          next unless shapes.any? { |sh| code.match?(sh) }

          "#{Pathname.new(path).relative_path_from(Rails.root)}:#{i + 1} — `.#{attr}` без `_label`\n      #{line.strip[0, 100]}"
        end
      end
    end

    expect(offenders).to be_empty, <<~MSG
      Вʼю друкує сире значення enum'а, хоч дім мітки існує:
        #{offenders.join("\n  ")}

      Парність міток у локалях стереже `enum_label_parity_spec` — і вона зелена
      навіть тоді, коли мітка бездоганна, а вʼю її не питає. Клич деривацію
      (`X.<attr>_label`), а не атрибут: дім один на застосунок, друга деривація
      означає, що друкарська помилка в одній із них лишиться зеленою назавжди.
    MSG
  end
end
