# frozen_string_literal: true

require "rails_helper"
require Rails.root.join("lib/silken_net/contrast")

# [UI.3] Гейт ЄДИНОГО індикатора фокуса — SC 1.4.11 (non-text contrast, бар 3:1).
#
# 🔴 Чому окремий гейт, хоч контраст уже має два прилади. Обидва сліпі до цієї
# осі ЗА ПОБУДОВОЮ, і кожен — по-своєму: браузерний збирач (`contrast_audit`)
# міряє пари ТЕКСТ/ФОН, а кільце фокуса малюється `box-shadow`, тобто ТІННЮ —
# виміряно 2026-08-19, форс `:focus-visible` дає НУЛЬ нових пар на всьому
# контурі; `design_token_existence_spec` судить ІСНУВАННЯ токена, ніколи його
# придатність для РОЛІ. Тобто єдиний спосіб, яким користувач клавіатури бачить,
# де він, не перевіряв ніхто.
#
# Вимір, що завів цей файл: `--gaia-primary` (бренд-емералд) проти світлих
# поверхонь дає **2.43** на `surface-base` і **2.54** на картці — обидва нижчі
# за 3:1, тобто в світлій темі індикатор фокуса не існував для вимоги. Темна при
# цьому чиста (7.99), і саме тому клас прожив: половина глядачів бачила справний
# екран (та сама асиметрія, заради якої друга палітра тримається як
# mutation-тест дизайн-системи, `04_04 §1`).
#
# 🧱 ГЕЙТ НА ЗНАЧЕННЯ, не на форму — і це вибір проти дешевшого. Лексична
# заборона («не вживай голий `ring-gaia-primary`») закодувала б ВИСНОВОК і
# мовчала б, якби значення самого токена змінили. Тут рахується сама пара, тож
# гейт переживає ре-палітрування: зміниш `--gaia-primary-strong` на щось бліде —
# почервоніє, не питаючи дозволу.
#
# 🔒 Стелі названо, інакше зелений читається як «фокус доступний»:
#   1. Судиться КОЛІР кільця проти поверхні, ніколи його ТОВЩИНА чи зміщення —
#      1.4.11 вимагає й площі, а `ring-2` проти `ring-1` цей файл не розрізняє.
#   2. Поверхні беруться з `@theme` — тобто ті, на яких кільце СТОЇТЬ ЗАЗВИЧАЙ.
#      Кнопка на кастомному фоні (градієнт, сира палітра) сюди не входить.
#   3. Це гейт токена, не рендеру: він не знає, чи кільце взагалі малюється
#      (`focus-visible:outline-none` без `ring-*` пройде мовчки).
RSpec.describe "[UI.3] Контраст індикатора фокуса (SC 1.4.11)", type: :model do
  # Константи свідомо через `let`, а не `CONST` у блоці: другий варіант
  # витікає в глобальний неймспейс і вже колідував би з `CSS_PATH` сусідньої
  # спеки — тобто дві перевірки мовчки ділили б одне значення.
  let(:css_path)       { Rails.root.join("app/assets/tailwind/application.css") }
  let(:non_text_bar)   { 3.0 }
  # Поверхні, на яких кільце реально стоїть: тло сторінки й тло картки/панелі.
  let(:surface_tokens) { %w[gaia-surface-base gaia-surface] }
  # НАБІР, а не один токен: деструктивна дія легітимно має власне кільце, і це
  # не послаблення — кожен член судиться ТИМ САМИМ порогом. Додаючи сюди третій,
  # додай і ВИМІР: перелік без числа є дозволом, а не правилом.
  # ⚠️ Вимір, що завів другий член: `--status-danger` (пастельний фон бейджа)
  # у ролі кільця дає 1.17 світла / 2.02 темна — тобто «токен існує» ≠ «токен
  # придатний для РОЛІ»; `-accent` дає 3.61 / 5.39.
  let(:ring_tokens)    { %w[gaia-primary-strong status-danger-accent] }

  # Значення читаються з `@theme`-джерела, а не з білду: білд віддає вже
  # згенеровані утиліти, а нам потрібна САМА декларація теми в обох її шафах.
  def css = @css ||= css_path.read

  # Світла шафа — `:root`; темна — блок під `prefers-color-scheme: dark`.
  # Розділяємо за позицією медіа-запиту, бо імена токенів у шафах ОДНАКОВІ.
  # 🔴 Якір СТРУКТУРНИЙ, і перша редакція помилилась рівно тим класом, який цей
  # файл і стереже: голий index("prefers-color-scheme: dark") знаходив КОМЕНТАР
  # за двісті рядків вище (і `@custom-variant` поруч), тож «світла шафа» виходила
  # порожньою. Тому якір — рядок, що ПОЧИНАЄТЬСЯ з `@media` і відкриває блок.
  def theme_halves
    @theme_halves ||= begin
      idx = css.index(/^@media[^{]*prefers-color-scheme:\s*dark[^{]*\{/)
      raise "темна шафа не знайдена — гейт міряв би одну тему двічі" if idx.nil?

      { light: css[0...idx], dark: css[idx..] }
    end
  end

  def token(name, half)
    m = theme_halves.fetch(half).scan(/--#{Regexp.escape(name)}:\s*([^;]+);/).last
    raise "токен `--#{name}` не оголошений у шафі #{half}" if m.nil?

    m.first.strip
  end

  # 🔴 Ліхтар на РОЗКОЛ, і він стоїть першим навмисно: половина, що вийшла
  # порожньою, зробила б решту або падінням «токен не оголошений», або — гірше —
  # виміром ОДНІЄЇ теми двічі під двома іменами. Саме це й сталося в першій
  # редакції, і коштувало одного прогону лише тому, що токен не знайшовся.
  it "обидві шафи теми несуть токени (розкол не виродився)" do
    %i[light dark].each do |half|
      count = theme_halves.fetch(half).scan(/--gaia-[a-z0-9-]+:/).size
      expect(count).to be >= 10,
                       "шафа #{half} несе #{count} токенів — розкол за медіа-запитом зламався"
    end
  end

  it "кільце фокуса тримає 3:1 проти кожної звичної поверхні в ОБОХ темах" do
    failures = %i[light dark].flat_map do |half|
      ring_tokens.flat_map do |ring_name|
        ring = token(ring_name, half)

        surface_tokens.filter_map do |surface_name|
          surface = token(surface_name, half)
          ratio = SilkenNet::Contrast.ratio(
            SilkenNet::Contrast.parse(ring), SilkenNet::Contrast.parse(surface)
          )
          next if ratio >= non_text_bar

          format("%s: --%s (%s) на --%s (%s) → %.2f (бар %.1f)",
                 half, ring_name, ring, surface_name, surface, ratio, non_text_bar)
        end
      end
    end

    expect(failures).to be_empty, <<~MSG
      Індикатор фокуса не досягає 1.4.11:
        #{failures.join("\n  ")}

      Це ЄДИНИЙ спосіб, яким користувач клавіатури бачить, де він. Ані браузерний
      збирач контрасту (міряє пари текст/фон, а кільце це ТІНЬ), ані гейт існування
      токена цього не бачать — тому поріг стоїть тут.
    MSG
  end

  # 🔴 Друга вісь, без якої перша стереже НЕ ТЕ: гейт вище судить токен
  # `gaia-primary-strong`, а розмітка вільна вживати будь-який інший. Без цього
  # прикладу можна повернути голий `--gaia-primary` у кільце, і перша перевірка
  # лишиться зеленою — вона просто міряла б токен, якого розмітка не вживає.
  it "розмітка вживає САМЕ той токен, який гейт судить" do
    offenders = Dir.glob(Rails.root.join("app/views/**/*.rb")).filter_map do |path|
      # ⚠️ Регекс мусить брати лише КОЛІРНІ утиліти: `ring-2`/`ring-0` це ТОВЩИНА,
      # `ring-offset-*` — зміщення, `ring-inset` — геометрія. Перша редакція брала
      # все підряд і звітувала товщину як хибний токен — прилад, що ПЕРЕбирає.
      hits = File.read(path).scan(/focus-visible:ring-([a-z][a-z0-9-]*)/).flatten.uniq
                 .reject { |t| t.start_with?("offset") || t == "inset" }
      wrong = hits.reject { |t| ring_tokens.include?(t) }
      next if wrong.empty?

      "#{Pathname.new(path).relative_path_from(Rails.root)}: #{wrong.join(', ')}"
    end

    expect(offenders).to be_empty, <<~MSG
      Кільце фокуса вживає токен, якого цей гейт не судить:
        #{offenders.join("\n  ")}

      Легальні кільця: #{ring_tokens.join(', ')}. Або переведи сайт на один із них,
      або додай новий у `ring_tokens` РАЗОМ із виміром — інакше перевірка вище
      стереже токен, якого на екрані немає.
    MSG
  end

  # Ліхтар на сам вимір: порожня множина сайтів зробила б приклад вище зеленим
  # на порожньому, тобто атестувала б рівно те, що мала виміряти.
  it "у дереві взагалі є індикатори фокуса (порожній скоуп ≠ успіх)" do
    total = Dir.glob(Rails.root.join("app/views/**/*.rb"))
               .sum { |p| File.read(p).scan("focus-visible:ring-").size }

    expect(total).to be >= 15,
                     "знайдено #{total} індикаторів фокуса — скоуп обвалився, обидва приклади вище вакуумні"
  end
end
