# frozen_string_literal: true

require "rails_helper"
require Rails.root.join("spec/support/contrast_registry")

# [UI.3] Сторож ПОПУЛЯЦІЇ контуру контрастності.
#
# 🔴 Клас, який він закриває, названий у шапці самого приладу
# (`spec/support/contrast_audit.rb`) і вже коштував хибного присуду: прилад
# міряє рівно ті сторінки, які йому дали, а перелік доти жив літералом усередині
# кожної спеки. Тобто НОВА сторінка не потрапляла у вимір ніколи, і ніщо про це
# не сигналило — «зелений контур» означав лише «здорові ті чотири, що я обрав».
# Тепер популяція деривується з `routes.rb`, і кожен її член мусить бути
# класифікований у реєстрі.
#
# 🧱 Форма — курована мапа, що ЛИШЕ СКОРОЧУЄТЬСЯ (взірець `browser_contour_json_spec`):
# запис не є дозволом, він несе ПІДСТАВУ і УМОВУ ПОВЕРНЕННЯ, і обидва поля
# гейтуються окремими прикладами.
#
# 🔒 Чого цей гейт НЕ бачить — стелі названо явно, інакше зелений читається як
# «поверхня доступна»:
#   1. Він про ПОПУЛЯЦІЮ, ніколи про пороги: чи проходить сторінка AA, судять
#      контур-спеки, не цей файл.
#   2. Він бачить МАРШРУТИ, не ЕКРАНИ. Сторінка з двома станами (порожній ⊥
#      наповнений) — один маршрут, і другий стан невидимий за побудовою.
#   3. Класифікація хвиль — ДЕКЛАРАЦІЯ людини. Гейт перевіряє, що вона є і що
#      вона несе підставу, ніколи — що вона ПРАВДИВА: «машинний» на екшені, який
#      віддає HTML, пройде. Саме тому шапка реєстру вимагає ВІДКРИТИ екшен, і
#      саме там записано, що мій власний здогад був хибний на 7 з 11.
#   4. Він не знає про ДОСЯЖНІСТЬ маршруту для актора: сторінка за
#      `authorize_super_admin!` віддасть `Errors::Page` на тому ж шляху, тобто
#      контур міряв би сторінку помилки, лишаючись зеленим.
#   5. POST/PATCH/DELETE поза скоупом: контраст міряється на тому, що ВИДНО,
#      а видно GET-відповідь.
RSpec.describe "[UI.3] Популяція контуру контрастності", type: :model do
  # Популяція деривується з РЕАЛЬНОГО роутера, ніколи з переліку — інакше гейт
  # звірявся б із власною копією світу (§Guard-craft #67: анкор має бути ЗОВНІШНІЙ).
  #
  # Фільтр мінімальний і оголошений: GET · має контролер · шлях не всередині
  # фреймворкового `/rails/` (ActiveStorage, Turbo-native, ViewComponent-preview).
  # Усе інше класифікує ЛЮДИНА в реєстрі — гейт наміру не виводить.
  def live_routes
    Rails.application.routes.routes.filter_map do |r|
      next unless r.verb.to_s.include?("GET")

      controller = r.defaults[:controller]
      next if controller.nil?
      next if r.path.spec.to_s.start_with?("/rails/")

      "#{controller}##{r.defaults[:action]}"
    end.uniq
  end

  let(:routes) { live_routes }

  # 🔴 Ліхтар на сам ВИМІР, і він стоїть ПЕРШИМ навмисно: усі приклади нижче
  # порівнюють множини, а порожня множина маршрутів зробила б їх усі зеленими
  # одночасно — рівно та форма хибно-зеленого, проти якої цей файл і написаний.
  # Поріг свідомо низький: він стереже ОБВАЛ деривації (перейменований API
  # роутера, порожній eager-load), а не кількість сторінок, яка легітимно росте.
  it "деривація популяції жива (порожній скоуп ≠ успіх)" do
    expect(routes.size).to be > 30,
                           "з роутера прийшло #{routes.size} GET-маршрутів — деривація зламана, решта прикладів вакуумна"
  end

  it "кожен браузерний маршрут КЛАСИФІКОВАНИЙ — новий не може тихо випасти з виміру" do
    unclassified = routes - ContrastRegistry::CLASSIFIED_KEYS

    expect(unclassified).to be_empty, <<~MSG
      Маршрути поза реєстром контрасту:
        #{unclassified.sort.join("\n  ")}

      Це не бюрократія: доти перелік сторінок жив літералом у спеці, тож нова
      сторінка не з'являлась у вимірі НІКОЛИ. Додай кожен у `ContrastRegistry` —
      або в контур (тоді прилад його реально відкриє), або у хвилю з `why`/`back`.
      ⚠️ Перед тим як назвати екшен «машинним» — ВІДКРИЙ його: здогад про це був
      хибний на семи з одинадцяти (див. шапку реєстру).
    MSG
  end

  it "реєстр не гниє — кожен його запис досі є живим маршрутом" do
    stale = ContrastRegistry::CLASSIFIED_KEYS - routes

    expect(stale).to be_empty, <<~MSG
      Записи реєстру без відповідного маршруту (екшен знято або переіменовано):
        #{stale.sort.join("\n  ")}
      Прибери рядок — інакше реєстр описує світ, якого вже немає, і його розмір
      більше не є твердженням про покриття.
    MSG
  end

  it "жоден маршрут не класифікований ДВІЧІ" do
    dupes = ContrastRegistry::CLASSIFIED_KEYS.tally.select { |_k, n| n > 1 }.keys

    expect(dupes).to be_empty, <<~MSG
      Маршрути у двох категоріях одночасно: #{dupes.join(', ')}.
      Тоді «хвиля спорожніла» перестає означати «сторінки виміряні» — запис
      лишається жити у другій категорії й тримає ілюзію класифікації.
    MSG
  end

  describe "підстава і умова повернення" do
    it "кожна хвиля несе змістовну підставу" do
      thin = ContrastRegistry::WAVES.select { |_k, w| w[:why].to_s.strip.length < 40 }
      expect(thin).to be_empty, "хвилі без підстави: #{thin.keys.join(', ')}"
    end

    it "кожна хвиля оголошує `back` — умову або явне :none" do
      undeclared = ContrastRegistry::WAVES.reject do |_k, w|
        w[:back] == :none || w[:back].to_s.strip.length >= 20
      end

      expect(undeclared).to be_empty, <<~MSG
        Хвилі без умови повернення: #{undeclared.keys.join(', ')}.
        `back:` — це подія, після якої записи звідси зникають, а сторінки стають
        must-measure. Якщо вимога до них незастосовна ЗА ПОБУДОВОЮ — напиши
        `back: :none` явно, і будь готовий це захистити.
      MSG
    end

    # `:none` тут не «я не придумав», а твердження «вимога незастосовна». Для
    # хвиль, заведених через ЧЕРГУ, воно хибне за визначенням: вони й існують
    # тому, що сторінку ЩЕ не виміряли. Дзеркало правила LATENT у взірця.
    it "постійне звільнення має право лише на те, що не рендерить HTML" do
      permanent = ContrastRegistry::WAVES.select { |k, w| w[:back] == :none && k != :machine }

      expect(permanent).to be_empty, <<~MSG
        #{permanent.keys.join(', ')} оголошені постійними, хоч сторінки там рендерять HTML.
        Постійним буває лише те, до чого 1.4.3 незастосовний за побудовою.
      MSG
    end

    it "кожна декларація декорації несе підставу й умову повернення" do
      bad = ContrastRegistry::DECORATIONS.reject do |_k, d|
        d[:why].to_s.strip.length >= 40 && d[:back].to_s.strip.length >= 20
      end

      expect(bad).to be_empty, <<~MSG
        Декорації без підстави або умови повернення: #{bad.keys.join(', ')}.
        «Чиста декорація» машинно не відрізняється від контенту (`aria-hidden`
        ховає від скрінрідера, не від ока), тож єдина чесна форма — явна
        декларація, яка вміє зникнути.
      MSG
    end
  end

  describe "контури не рекламують покриття, якого немає" do
    it "кожен контур указує на СПЕКУ, що існує" do
      missing = ContrastRegistry::CONTOURS.reject { |_k, c| Rails.root.join(c[:spec]).exist? }
      expect(missing).to be_empty, "контури без спеки: #{missing.keys.join(', ')}"
    end

    # 🔴 Без цього прикладу `CONTOURS` був би просто ЗАЯВОЮ про покриття. Спека
    # мусить читати перелік ЗВІДСИ — інакше реєстр роками рекламує сторінку,
    # якої прилад не відкриває, і жоден інший приклад цього не бачить.
    it "кожна контур-спека читає перелік із реєстру, а не тримає власний літерал" do
      detached = ContrastRegistry::CONTOURS.reject do |slug, c|
        source = Rails.root.join(c[:spec]).read
        source.include?("ContrastRegistry.paths_for(:#{slug}")
      end

      expect(detached).to be_empty, <<~MSG
        Контури, чия спека не бере шляхи з реєстру: #{detached.keys.join(', ')}.
        Поки перелік дублюється в спеці, `CONTOURS` є заявою, а не фактом: два
        переліки розходяться мовчки, і реєстр показує ширше покриття, ніж є.
      MSG
    end

    it "кожен вимірюваний маршрут будує шлях без винятку" do
      ctx = { cluster: Struct.new(:id).new(1), tree: Struct.new(:id).new(2), reset_token: "t0ken" }

      ContrastRegistry::CONTOURS.each_key do |slug|
        paths = ContrastRegistry.paths_for(slug, ctx)
        expect(paths).to all(start_with("/")), "контур #{slug} побудував шлях без провідного «/»"
      end
    end
  end
end
