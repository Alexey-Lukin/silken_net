# 🔴 Твердження про ЗРОБЛЕНЕ не сміє нести дату, якої ще не було.
#
# Клас виміряно 2026-08-17: у корпусі стояло **17** дат попереду реального
# «сьогодні» — у трекері, каноні `04_06` і ТРЬОХ скілах, — і майже всі внесені
# однією добою (2026-08-11) із зсувом на тиждень уперед. Тобто це не описка, а
# систематичний дрейф: сесія, що пише запис, не має надійного джерела поточної
# дати й підставляє здогад.
#
# 🔴 ЧОМУ ЦЕ НЕ КОСМЕТИКА, і ціна не гіпотетична. Дата в цьому корпусі є
# ОПОРОЮ ВПОРЯДКУВАННЯ: власний рефлекс роботи з трекером каже «візьми дату
# знахідки з тіла пункту й прогрепай присуди, ПІЗНІШІ за неї». Запис, датований
# наперед, робить старіший присуд «новішим» за той, що його спростовує, — і
# промах тихий. Дзеркально на боці читача: `✅ ЗАКРИТО <завтра>` читається як
# СВІЖІШЕ за коректно датоване, тобто хибна дата купує собі БІЛЬШЕ довіри.
#
# 🔒 ЯКІР — ЗОВНІШНІЙ, і це навмисно (§Guard-craft #67): порівняння йде з датою
# HEAD-коміта, а не з нашою ж прозою чи з константи в цьому файлі. Дзеркало
# вчорашнього уроку — гейт, що звіряє два наші доми між собою, сліпий до того,
# що обидва помиляються однаково.
#
# 🔒 ДИСКРИМІНАТОР — дві ФОРМИ, обидві означають минуле, обидві статично видимі:
#   · завершальний маркер у рядку (`ЗАКРИТО` · `ШИПНУТО` · `ЗБУДОВАНО` …);
#   · провенанс-дужка `(<ID>, <дата>)` — конвенція корпусу для «знайдено тоді-то».
# Регуляторні дати набуття чинності (CRA/EU: «з 2027-12-11») не мають жодної з
# них і проходять — саме тому гейт не потребує реєстру винятків, що гниє.
#
# ⚠️ 2026-09-01: у цієї стелі знайдено НЕОГОЛОШЕНУ передумову — «одна клауза на
# рядок». Дискримінатор порядковий: рядок, що МІСТИТЬ маркер завершення, віддає
# гейту ВСІ свої дати. У `docs/00_07` нога є одним markdown-рядком із десятком
# клауз, тож легітимна майбутня дата (вікно free-trial Grafana), дописана до
# ноги, яка окремою клаузою рапортує `ЗАКРИТО 2026-08-31`, читається як
# твердження про зроблене. Тобто на цьому файлі майбутня дата фактично
# НЕПРЕДСТАВНА на будь-якій нозі, що бодай щось закриває — а таких там більшість.
# 🔒 Присуд — стеля лишається, реєстр винятків так само не заводиться, а вимога
# перекладається на ФОРМУ запису: подія з майбутньою датою заводиться ОКРЕМОЮ
# ногою (`DEPLOY-1` → `Grafana-вікно`), і це не обхід гейта, а краща форма
# трекера незалежно від нього — чекбокс несе лише відкрите, а дедлайн відкритий
# за визначенням. 🔴 Загальний урок про гейти: перевіряючи оголошену стелю,
# питай не «чи вона правдива», а «на якій ГРАНУЛЯРНОСТІ вона правдива» —
# тут вона істинна для речення й хибна для рядка, і корпус вимірює рядками.
#
# 🔒 Стелі, названі поіменно:
#   · +1 доба допуску — зсув таймзони між автором коміта й записом не є дрейфом;
#     гейт ловить систематичне (дні-тижні), не межу доби;
#   · майбутня дата в БУДЬ-ЯКІЙ іншій формі невидима за побудовою;
#   · судиться ДАТА, ніколи правдивість самого твердження.
module FutureDatedClaimGate
  GLOBS = [ "docs/**/*.md", ".claude/**/*.md", "CLAUDE.md" ].freeze
  DATE  = /\b20\d\d-\d\d-\d\d\b/
  COMPLETION = /ЗАКРИТО|ШИПНУТО|ЗБУДОВАНО|ЗАГАРТОВАНО|ратифіковано|(?:пере)?виміряно|знято|closed|shipped/i
  # `(ARCH.84, 2026-08-18)` / `(UI.11, 2026-08-19)` — ID, кома, дата.
  # 🔴 КВАДРАТНА форма додана 2026-08-19 і не є косметикою: вимір на власному
  # рецидиві показав, що гейт ловив **2 порушення з 30**. Решта 28 їхали як
  # `[UI.1, 2026-08-20]` — тег-провенанс у КВАДРАТНИХ дужках, який дужкова форма
  # не бачить, а дієслова завершення в тому рядку немає (це коментар у коді або
  # шапка спеки). Тобто дискримінатор покривав ~7% реальної популяції, і саме
  # тому дефект пройшов у трьох комітах поспіль. ⚠️ Клас ширший за регекс:
  # **форма ПРОВЕНАНСУ в цьому корпусі має два написання, і гейт знав одне** —
  # перевіряючи будь-який гейт «за формою», грепни ОБИДВА написання, перш ніж
  # повірити його нулю.
  PROVENANCE = /[(\[]\s*[A-Z][A-Z0-9]*[.\-][\w.]+[^)\]]{0,60}?,\s*20\d\d-\d\d-\d\d/

  module_function

  # Дата HEAD-коміта +1 доба допуску. Порожній вивід (не-git-дерево) робить
  # гейт нездатним судити — і тоді він мусить сказати це вголос, а не мовчати.
  def anchor
    out = Dir.chdir(REPO_ROOT) { `git log -1 --format=%ad --date=short 2>/dev/null` }.strip
    out.empty? ? nil : Date.parse(out) + 1
  end

  def scanned_dates
    files.sum { |f| File.read(f).scan(DATE).size }
  end

  def files
    GLOBS.flat_map { |g| Dir[REPO_ROOT.join(g)] }.select { |f| File.file?(f) }.sort
  end

  def violations
    bar = anchor or return []

    files.flat_map do |path|
      rel = Pathname(path).relative_path_from(REPO_ROOT).to_s
      File.readlines(path).each_with_index.flat_map do |line, idx|
        next [] unless line.match?(COMPLETION) || line.match?(PROVENANCE)

        line.scan(DATE).filter_map do |d|
          next if Date.parse(d) <= bar

          "#{rel}:#{idx + 1}: `#{d}` — твердження про зроблене, датоване пізніше за HEAD (#{bar - 1})"
        end
      end
    end
  end
end

RSpec.describe "твердження про зроблене не датується майбутнім" do # rubocop:disable RSpec/DescribeClass
  # Ліхтар на ОБИДВА боки виміру: якір здобувається, і корпус справді насичений
  # датами. Без цього «нуль порушень» означало б «нема з чим порівнювати» —
  # рівно той клас, який гейт і ловить.
  it "має живий якір і непорожній корпус дат" do
    expect(FutureDatedClaimGate.anchor).to be_a(Date),
      "git не віддав дату HEAD — гейт не здатен судити, і мовчати про це не має права"
    expect(FutureDatedClaimGate.files.size).to be > 40
    expect(FutureDatedClaimGate.scanned_dates).to be > 100
  end

  it "не має жодного запису, датованого пізніше за HEAD" do
    violations = FutureDatedClaimGate.violations

    expect(violations).to be_empty, <<~MSG
      Записи про ВИКОНАНЕ несуть дату, якої ще не було. Дата в корпусі є опорою
      впорядкування («грепни присуди, пізніші за цю»), тож зсув уперед робить
      старіший присуд «новішим» за той, що його спростовує.

      Лік: візьми справжню дату з git, а не з голови —
        git log -1 --format=%ad --date=short          (сьогодні)
        git log -S"<рядок>" --format=%ad --date=short -- <файл>   (коли внесено)

      #{violations.join("\n")}
    MSG
  end
end
