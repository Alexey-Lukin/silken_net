# ⚖️ Присуд власника 2026-08-21 (`00_07` ARCH.59). Доти в дереві жив другий шлях —
# `InsightGeneratorService.cleanup_old_logs!`, тобто `delete_all` батчами по рядках,
# старших за сім днів. Він був мертвий (єдиний викликач — колбек `Sidekiq::Batch`,
# а Pro-ліцензії немає), і саме тому небезпечний: покупка ліцензії озброїла б його
# МОВЧКИ, без окремого рішення — той самий клас, що `expires_in` на uplink.
#
# 🔴 Чому один механізм, а не «два не заважають». Тракт архіву вже очікує саме дропу
# й має для нього чесний стан: `TelemetryArchiveBatch.retention_expired` означає
# «листя менше за `leaf_count`, бо партиції дропнуто — НЕ tamper». Другий спосіб
# зникнення рядків зробив би цей статус НЕОДНОЗНАЧНИМ, тобто зіпсував би єдиний
# прилад, яким ми відрізняємо ретеншн від підміни. Плюс дві ціни семиденного вікна,
# виміряні окремо: `Mrv::LineageReportService` гілки «джерельні рядки застаріли» не
# має взагалі й видав би аудиторові `unprovable_regrouped` («дерево змінило
# кластер»), а пін архівного батча їде чергою `low` — видалення встигало б його
# випередити, лишивши on-chain `archiveRoot` без офчейн-свідка.
#
# 🔒 **Порожня множина тут — МЕТА, а не провал** (`ssot-maintenance` §Guard-craft #61),
# тож живість доводить не популяція, а детектор: мутація «додати `delete_all` над
# TelemetryLog» червонить приклад і називає файл. Ліхтар на сам скан стоїть окремо —
# інакше переїзд каталогів дав би «0 порушень» на нулі прочитаних файлів.
#
# ⚠️ Каскад `Tree has_many :telemetry_logs, dependent: :delete_all` НЕ є порушенням і
# свідомо поза скоупом: він спрацьовує від знищення БАТЬКА, а не від віку рядка, і
# декларується, а не викликається. Дискримінатор саме такий — ВИКЛИК проти
# ДЕКЛАРАЦІЇ, бо ретеншн за побудовою є викликом.
#
# Механізм дропу — `00_07` ARCH.70; канон retention-чесності — `04_01 §11`.
RSpec.describe "raw telemetry retention has exactly one mechanism" do # rubocop:disable RSpec/DescribeClass
  # Форму пишемо ЗБІРКОЮ, а не літералом: рядок-зразок у цьому файлі сам був би
  # хітом власного сканера (той самий податок, що на будь-який текст про форму,
  # яку гейт забороняє — `ssot-maintenance` §Guard-craft #10a).
  #
  # 🔴 Клас анкера, куплений мутацією ПРИ НАПИСАННІ цього гейта: тут стояло
  # `[^\n)]*`, і воно виключало закриваючу дужку — тобто регекс не бачив
  # НАЙЗВИЧАЙНІШОЇ форми виклику, бо між іменем і `delete_all` майже завжди
  # стоїть `.where(…)`. Гейт був зелений на вставленому порушенні, тобто
  # декоративний від народження. Тіло рядка обмежує лише перенос.
  let(:destructive_call) { /TelemetryLog[^\n]*\.\s*(?:#{%w[delete_all destroy_all].join('|')})/ }
  let(:scanned_trees)    { %w[app lib] }

  let(:ruby_files) do
    scanned_trees.flat_map { |tree| Dir[Rails.root.join(tree, "**", "*.rb")] + Dir[Rails.root.join(tree, "**", "*.rake")] }
  end

  it "reads a non-empty population (otherwise a green run means nothing)" do
    expect(ruby_files.size).to be > 200,
      "скан не знайшов Ruby-файлів у #{scanned_trees.join('/')} — «0 порушень» тут означало б «0 перевірок»"
  end

  it "carries no age-based delete path over telemetry_logs" do
    offenders = ruby_files.select do |path|
      # Коментарі не рахуються: цей файл і шапка сервісу ОПИСУЮТЬ заборонену форму,
      # і опис не є її вживанням.
      code = File.readlines(path).reject { |line| line.lstrip.start_with?("#") }.join
      code.match?(destructive_call)
    end

    expect(offenders).to be_empty,
      "прямий delete-шлях над `telemetry_logs` повернувся у " \
      "#{offenders.map { |f| f.sub("#{Rails.root}/", '') }.join(', ')}. " \
      "Ретеншн сирої телеметрії робить ВИКЛЮЧНО дроп місячних партицій (`00_07` ARCH.59 ⚖️ 2026-08-21): " \
      "другий механізм зникнення рядків робить `TelemetryArchiveBatch.retention_expired` неоднозначним, " \
      "тобто псує єдиний прилад, яким ми відрізняємо ретеншн від підміни"
  end
end
