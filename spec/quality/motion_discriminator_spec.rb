# frozen_string_literal: true

require "rails_helper"

# [UI.3] Гейт на РУХ як носій сенсу — два різні дефекти одного кореня.
#
# 🔴 Чому це не косметика. Застосунок несе глобальне правило
# `@media (prefers-reduced-motion: reduce)`, яке ставить
# `animation-duration: 0.01ms !important` на ВСЕ. Тобто будь-яка анімація для цієї
# когорти просто не існує — і клас, що покладається на неї, для них порожній.
# Виміряно 2026-08-19: `animate-pulse` був ЄДИНИМ, чим `processing`,
# `manual_review` і `updating` відрізнялись від `pending` у спільному реєстрі
# станів, тож для reduced-motion усі чотири бейджі були байтово однакові — і
# серед них `manual_review`, тобто double-spend guard (кошти заблоковані,
# потрібна людина) виглядав рутинним «в обробці».
#
# ⊕ Друга вісь — той самий рух, але інша шкода: `animate-pulse` міняє `opacity`
# ВСЬОГО вузла, тож на вузлі З ТЕКСТОМ підпис половину часу нечитабельний
# (виміряно: 6.37 → 2.26 при барі 4.5). Це поза зором обох приладів контрасту:
# статичний шукає `opacity-N`, а браузерний свідомо глушить анімації — інакше
# число стало б функцією моменту зчитування.
#
# 🔒 Стелі названо, інакше зелений читається ширше:
#   1. Перша вісь судить ОДИН реєстр (`StatusBadge::STYLES`) — приватні мапи
#      компонентів не мають спільної форми, тож їх ловить лише друга вісь.
#   2. Друга вісь ловить рух поруч із КОЛІРНИМ токеном тексту в одному рядку
#      класів; пульс на сусідньому вузлі, що успадкував колір, вона не бачить.
#   3. Гейт про ДИСКРИМІНАЦІЮ і ЧИТАБЕЛЬНІСТЬ, не про доречність руху: пульс
#      на чистій декорації (LED-крапка, скелетон, SVG-штрих) легітимний і тут
#      не судиться — таких у дереві більшість.
RSpec.describe "[UI.3] Рух не сміє бути носієм сенсу", type: :model do
  # Свідомо через `let`, не `CONST`: другий варіант витікає в глобальний
  # неймспейс (rubocop `RSpec/LeakyConstantDeclaration`), і сусідня спека вже
  # колідувала так само — дві перевірки мовчки ділили б одне значення.
  let(:motion) { /\s*\banimate-[a-z0-9-]+\b/ }
  # Колірна утиліта тексту, а не будь-яка `text-*`: `text-tiny`/`text-lg` — це
  # РОЗМІР, і гейт, що червонів би на них, зняли б першим.
  let(:text_colour) do
    /\btext-(?:status|gaia|token)-[a-z-]+\b|\btext-(?:red|amber|emerald|blue|zinc|gray|white|black)(?:-\d+)?\b/
  end

  # ─────────────────────────────────────────────────────────────────────────────
  # Вісь 1 — дискримінація станів
  # ─────────────────────────────────────────────────────────────────────────────
  describe "реєстр станів (`StatusBadge::STYLES`)" do
    let(:styles) { Views::Shared::UI::StatusBadge::STYLES }

    # Ліхтар: порожній чи однорідний реєстр зробив би перевірку нижче вакуумною.
    it "реєстр непорожній і справді розрізняє стани" do
      expect(styles.size).to be >= 15
      expect(styles.values.uniq.size).to be >= 6
    end

    # 🔴 Пари, РІВНІ після зняття руху, але різні до нього. Саме ця форма — а не
    # «усі значення унікальні»: однакові стилі в РІЗНИХ доменах легітимні й уже
    # є (`pending` ⊥ `dormant` — обидва warning, обидва «чекає», обидва без руху).
    # Порушення = рух ставав єдиною різницею, тобто зникав разом із когортою.
    it "жоден стан не відрізняється від іншого ЛИШЕ рухом" do
      collapsed = styles.transform_values { |v| v.gsub(motion, "").strip }

      offenders = styles.keys.combination(2).filter_map do |a, b|
        next if styles[a] == styles[b]
        next unless collapsed[a] == collapsed[b]

        "#{a} ⊥ #{b} — обидва зводяться до `#{collapsed[a]}`"
      end

      expect(offenders).to be_empty, <<~MSG
        Рух є ЄДИНИМ дискримінатором між станами:
          #{offenders.join("\n  ")}

        Для `prefers-reduced-motion` анімацій немає (глобальне правило в
        `application.css` ставить `animation-duration: 0.01ms !important`), тож ці
        стани для цілої когорти глядачів невідрізнимі. Дай кожному СТАТИЧНИЙ
        безкольоровий дискримінатор — родина вже є в цьому ж реєстрі
        (`line-through` · `italic` · `ring-2 ring-current`).
      MSG
    end
  end

  # ─────────────────────────────────────────────────────────────────────────────
  # Вісь 2 — читабельність підпису під анімацією
  # ─────────────────────────────────────────────────────────────────────────────
  describe "рух на вузлі, що несе текст" do
    it "жоден клас-рядок не поєднує анімацію з колірним токеном тексту" do
      offenders = Dir.glob(Rails.root.join("app/views/**/*.rb")).flat_map do |path|
        File.readlines(path).each_with_index.filter_map do |line, i|
          next if line.lstrip.start_with?("#")
          next unless line.match?(motion) && line.match?(text_colour)

          "#{Pathname.new(path).relative_path_from(Rails.root)}:#{i + 1} — #{line.strip[0, 90]}"
        end
      end

      expect(offenders).to be_empty, <<~MSG
        Анімація стоїть на вузлі, що задає колір ТЕКСТУ:
          #{offenders.join("\n  ")}

        `animate-pulse` міняє `opacity` усього вузла, тож підпис половину часу
        нечитабельний (виміряно: 6.37 → 2.26 при барі 4.5), і жоден із двох
        приладів контрасту цього не бачить за побудовою. Перенеси рух на
        сусідній `aria-hidden` вузол без тексту, або зніми — сенс мусить нести
        статичний дискримінатор.
      MSG
    end

    # Ліхтар на скоуп: якби glob нічого не бачив, приклад вище був би зелений
    # на порожньому — і саме так виглядав би зламаний шлях.
    it "у дереві взагалі є анімації (порожній скоуп ≠ успіх)" do
      total = Dir.glob(Rails.root.join("app/views/**/*.rb"))
                 .sum { |p| File.read(p).scan(/\banimate-[a-z0-9-]+\b/).size }

      expect(total).to be >= 10,
                       "знайдено #{total} анімацій — скоуп обвалився, приклад вище вакуумний"
    end
  end
end
