# frozen_string_literal: true

require "rails_helper"

# [UI.3] Гейт на РУХ як носій сенсу — два різні дефекти одного кореня.
#
# 🔴 Чому це не косметика. Застосунок несе глобальне правило
# `@media (prefers-reduced-motion: reduce)`, яке ставить
# `animation-duration: 0.01ms !important` на ВСЕ. Тобто будь-яка анімація для цієї
# когорти просто не існує — і клас, що покладається на неї, для них порожній.
# Виміряно 2026-08-19: `animate-pulse` був ЄДИНИМ, чим `processing`,
# `manual_review` і `updating` відрізнялись від `pending` у спільному реєстрі
# станів — включно з `manual_review`, тобто double-spend guard'ом (кошти
# заблоковані, потрібна людина).
#
# ⚠️ **ТОЧНА рамка, і перша редакція цієї шапки її ЗАВИЩУВАЛА** (виправлено
# 2026-08-20 після adversarial-проходу, який успадкував те саме завищення).
# Однаковим ставав РЯДОК СТИЛЮ, не відрендерений бейдж: `StatusBadge` завжди
# друкує власний підпис, і вони різні («pending» ⊥ «processing» ⊥ «manual
# review» ⊥ «updating»), тож РОЗРІЗНЮВАНІСТЬ не втрачалась і SC 1.4.1 (Use of
# Color) задоволений текстом. Втрачалась **ПОМІТНІСТЬ** — єдиний маркер, яким
# гучний стан ловить око оператора при скануванні таблиці на двадцять рядків.
# Це слабша заява, ніж «невідрізнимі», і саме вона правдива; вердикт (кожному
# стану статичний дискримінатор) від цього не змінюється, бо ціль тут — щоб
# `manual_review` було ВИДНО, а не щоб його можна було прочитати.
#
# ⊕ Друга вісь — той самий рух, але інша шкода: `animate-pulse` міняє `opacity`
# ВСЬОГО вузла, тож на вузлі З ТЕКСТОМ підпис половину часу нечитабельний.
# ⚠️ **Числа й їхня АТРИБУЦІЯ виправлені 2026-08-20** — доти тут стояло «6.37 → 2.26»
# без теми, поруч із сусіднім рядком, що аргументує від ТЕМНОЇ як «єдиної уживаної»:
# насправді 6.37 → ~2.28 це СВІТЛА тема, а темна дає 7.28 → ~3.1–3.3. Обидві нижчі
# за 4.5, тож вердикт вистояв, а доказ був узятий з однієї теми й поданий як
# загальний. ⊕ І слово «виміряно» тут означає ПОРАХОВАНО РУКАМИ: браузерний прилад
# цього числа не бачить за побудовою двічі — він відкидає предків з `opacity < 1` як
# `unmeasurable/opacity_group` і сам форсує `prefers-reduced-motion: reduce`, тобто
# западини не існує в його світі. Статичний шукає `opacity-N` і теж сліпий.
#
# 🔒 Стелі названо, інакше зелений читається ширше:
#   1. Перша вісь судить ОДИН реєстр (`StatusBadge::STYLES`) — приватні мапи
#      компонентів не мають спільної форми, тож їх ловить лише друга вісь.
#   2. Друга вісь ловить рух поруч із колірним токеном тексту В ОДНОМУ РЯДКУ —
#      і межа саме РЯДКОВА, не міжвузлова, як тут стояло доти (виправлено
#      2026-08-20). Той самий `span` із багаторядковим `tokens(...)`, де колір у
#      першому аргументі, а `"animate-pulse": cond` у другому, гейтом не бачиться;
#      багаторядкових `tokens(` у дереві вже пʼять. Пульс на сусідньому вузлі,
#      що успадкував колір, вона теж не бачить.
#   3. Гейт про ДИСКРИМІНАЦІЮ і ЧИТАБЕЛЬНІСТЬ, не про доречність руху: пульс
#      на чистій декорації (LED-крапка, скелетон, SVG-штрих) легітимний і тут
#      не судиться — таких у дереві більшість.
RSpec.describe "[UI.3] Рух не сміє бути носієм сенсу", type: :model do
  # Свідомо через `let`, не `CONST`: другий варіант витікає в глобальний
  # неймспейс (rubocop `RSpec/LeakyConstantDeclaration`), і сусідня спека вже
  # колідувала так само — дві перевірки мовчки ділили б одне значення.
  # ⚠️ Дві правки, обидві з adversarial 2026-08-20. (а) `animate-[pulse_2s_infinite]`
  # — документована arbitrary-форма v4, і після `animate-` там стоїть `[`, тож
  # `[a-z0-9-]+` її НЕ ловив: той самий дефект, повернутий цим синтаксисом, проходив
  # зеленим. (б) `animate-none` це ВІДСУТНІСТЬ руху, тож рахувати його рухом — хибний
  # червоний; виключено явно.
  let(:motion) { /\s*\banimate-(?!none\b)(?:\[[^\]]*\]|[a-z0-9-]+)/ }
  # Колірна утиліта тексту, а не будь-яка `text-*`: `text-tiny`/`text-lg` — це
  # РОЗМІР, і гейт, що червонів би на них, зняли б першим.
  let(:text_colour) do
    /\btext-(?:status|gaia|token)-[a-z-]+\b|\btext-(?:red|amber|emerald|blue|zinc|gray|white|black)(?:-\d+)?\b/
  end

  # ─────────────────────────────────────────────────────────────────────────────
  # Вісь 1 — дискримінація станів
  # ─────────────────────────────────────────────────────────────────────────────
  describe "реєстр станів (`StatusBadge::STYLES`)" do
    let(:styles) { Views::Shared::UI::StatusBadge::STYLES }

    # Ліхтар: порожній чи однорідний реєстр зробив би перевірку нижче вакуумною.
    it "реєстр непорожній і справді розрізняє стани" do
      expect(styles.size).to be >= 15
      expect(styles.values.uniq.size).to be >= 6
    end

    # 🔴 Пари, РІВНІ після зняття руху, але різні до нього. Саме ця форма — а не
    # «усі значення унікальні»: однакові стилі в РІЗНИХ доменах легітимні й уже
    # є (`pending` ⊥ `dormant` — обидва warning, обидва «чекає», обидва без руху).
    # Порушення = рух ставав єдиною різницею, тобто зникав разом із когортою.
    it "жоден стан не відрізняється від іншого ЛИШЕ рухом" do
      collapsed = styles.transform_values { |v| v.gsub(motion, "").strip }

      offenders = styles.keys.combination(2).filter_map do |a, b|
        next if styles[a] == styles[b]
        next unless collapsed[a] == collapsed[b]

        "#{a} ⊥ #{b} — обидва зводяться до `#{collapsed[a]}`"
      end

      expect(offenders).to be_empty, <<~MSG
        Рух є ЄДИНИМ дискримінатором між станами:
          #{offenders.join("\n  ")}

        Для `prefers-reduced-motion` анімацій немає (глобальне правило в
        `application.css` ставить `animation-duration: 0.01ms !important`), тож для
        цілої когорти ці стани втрачають ЄДИНИЙ маркер помітності — прочитати їх
        усе одно можна за підписом, а от ЗАУВАЖИТИ гучний стан у довгій таблиці ні.
        Дай кожному СТАТИЧНИЙ дискримінатор — родина вже є в цьому ж реєстрі
        (`line-through` · `italic` · `outline-2 outline-current`).
      MSG
    end
  end

  # ─────────────────────────────────────────────────────────────────────────────
  # Вісь 1б — дискримінатор, який гасить ІНШЕ користувацьке налаштування
  # ─────────────────────────────────────────────────────────────────────────────
  describe "дискримінатор переживає `forced-colors`" do
    let(:styles) { Views::Shared::UI::StatusBadge::STYLES }

    # 🔴 Друге налаштування, друга порожнеча. CSS Color Adjust L1 у режимі
    # `forced-colors` примусово ставить `box-shadow: none` — а `ring-*` у Tailwind
    # реалізовано саме через `--tw-ring-shadow` (перевірено в зібраному CSS).
    # Тобто дискримінатор на кільці зникає рівно так само, як анімація зникає для
    # `prefers-reduced-motion`, і саме на цьому кільці стояв `manual_review`.
    # `outline`, `font-style` і `text-decoration` у тому режимі виживають
    # (перефарбовуються в системний колір), тож `italic`/`line-through`/`outline`
    # стійкі. ⚠️ Рамка та сама, що у вісі 1: втрата ПОМІТНОСТІ, не розрізнюваності —
    # підпис бейджа friendly до обох режимів і завжди на місці.
    # ⛔ Кольори тут не судяться: forced-colors перефарбовує і фон, і текст, тож
    # ЖОДНА колірна різниця його не переживає — вимагати цього означало б
    # заборонити дизайн-систему цілком. Гейт вимагає лише, щоб стан, який має
    # дискримінатор ПОВЕРХ кольору, не спирався на самий box-shadow.
    it "жоден стан не спирається на box-shadow як на єдиний дискримінатор" do
      # ⚠️ Множина знімається ВУЗЬКО, і межа куплена негативним контролем:
      # `shadow-lg`/`-sm` — це ПІДНЕСЕННЯ (декор), і гейт, що читав би його
      # дискримінатором, червонів би на декоративній тіні, доданій одному членові
      # групи однакових стилів. Arbitrary `shadow-[…]` натомість у цьому дереві
      # завжди СЯЙВО-сигнал (`shadow-[0_0_8px_red]` на LED), тож лишається.
      removable = /\s*\b(?:animate-[a-z0-9-]+|ring(?:-[a-z0-9-]+)?|shadow-\[[^\]]*\])/
      collapsed = styles.transform_values { |v| v.gsub(removable, "").strip }

      offenders = styles.keys.combination(2).filter_map do |a, b|
        next if styles[a] == styles[b]
        next unless collapsed[a] == collapsed[b]

        "#{a} ⊥ #{b} — різниця зникає, коли зняти рух і box-shadow"
      end

      expect(offenders).to be_empty, <<~MSG
        Дискримінатор стану тримається на `box-shadow` (`ring-*`/`shadow-*`):
          #{offenders.join("\n  ")}

        Режим `forced-colors` гасить `box-shadow` цілком, тож для цієї когорти
        маркер зникає. Стійкі носії: `outline-*` · `italic` · `line-through`
        (`outline` перефарбовується, але лишається).
      MSG
    end
  end

  # ─────────────────────────────────────────────────────────────────────────────
  # Вісь 2 — читабельність підпису під анімацією
  # ─────────────────────────────────────────────────────────────────────────────
  describe "рух на вузлі, що несе текст" do
    # 🔴 ОДИН glob на приклад і ліхтар. Доти ліхтар переоголошував власний літерал,
    # тож друкарська помилка у шляху ВИМІРЮВАНОГО приклада його не зачіпала — він
    # і далі бачив свої анімації й лишався зеленим (adversarial 2026-08-20 довів
    # прогоном). Пара «гейт + ліхтар» міряла два різні обʼєкти.
    let(:view_files) { Dir.glob(Rails.root.join("app/views/**/*.rb")) }

    it "жоден клас-рядок не поєднує анімацію з колірним токеном тексту" do
      offenders = view_files.flat_map do |path|
        File.readlines(path).each_with_index.filter_map do |line, i|
          next if line.lstrip.start_with?("#")
          next unless line.match?(motion) && line.match?(text_colour)

          "#{Pathname.new(path).relative_path_from(Rails.root)}:#{i + 1} — #{line.strip[0, 90]}"
        end
      end

      expect(offenders).to be_empty, <<~MSG
        Анімація стоїть на вузлі, що задає колір ТЕКСТУ:
          #{offenders.join("\n  ")}

        `animate-pulse` міняє `opacity` усього вузла, тож підпис половину часу
        нечитабельний (виміряно: 6.37 → 2.26 при барі 4.5), і жоден із двох
        приладів контрасту цього не бачить за побудовою. Перенеси рух на
        сусідній `aria-hidden` вузол без тексту, або зніми — сенс мусить нести
        статичний дискримінатор.
      MSG
    end

    # Ліхтар на скоуп: якби glob нічого не бачив, приклад вище був би зелений
    # на порожньому — і саме так виглядав би зламаний шлях.
    it "у дереві взагалі є анімації (порожній скоуп ≠ успіх)" do
      total = view_files.sum { |p| File.read(p).scan(motion).size }

      expect(total).to be >= 10,
                       "знайдено #{total} анімацій — скоуп обвалився, приклад вище вакуумний"
    end
  end
end
