require "rails_helper"

# Гейт ЯВНОГО ФОРМАТУ: `decimal`-колонка (або аліас над нею) не сміє потрапляти
# в Phlex-блок голою — там вона друкується сирою точністю схеми, а не тим
# форматом, який обрав дизайн (`04_04 §2`).
#
# 🔴 ПІДСТАВА ЗМІНИЛАСЬ 2026-08-12, і це не косметика — читай далі, перш ніж
# посилатись на цей гейт. Народився він як гейт РЕНДЕРОВНОСТІ: Phlex друкував
# `BigDecimal` ПОРОЖНІМ рядком, тож `Trees::Show` малював порожнім `text-6xl`
# Z-координату і баланс. Ту причину знято в корені — `ApplicationComponent`
# заповнив Phlex-хук `format_object` для всього роду `Numeric`, тож голий
# BigDecimal тепер друкується, і **зникнення значення більше не є режимом
# відмови цього класу**. Носій кореневого ліку — `spec/views/components/
# application_component_spec.rb` (мутація-перевірено чотирма ходами).
#
# Тому гейт лишається, але стереже ІНШУ властивість: `{ w.balance }` дає
# «13013.0» — число без роздільників, без валюти й із хвостовим нулем, тобто
# формат за замовчуванням схеми. Сусідній `00_07` ARCH.88 саме про це:
# ті самі поля рендеряться `.round(2)`/`.round(4)`/`.round(6)` у трьох
# компонентах при колонці `numeric(24,6)`.
#
# ⚠️ Що НЕ рятує: `.round(2)` — на BigDecimal він повертає BigDecimal.
# Рятують `.to_f`/`.to_i`/`.to_s`, `.round` без аргументу, інтерполяція та i18n.
#
# 🔴 **Суперечність із `.to_f` реальна, присуд ухвалено, а вимір перевернув
# ОБСЯГ роботи — читай перед тим, як додавати `.to_f` за вимогою гейта.**
# Після кореневого ліку `.to_f` на звичайних значеннях не змінює НІЧОГО
# (`BigDecimal#to_s` і `.to_f.to_s` побайтово рівні: «28.7», «13013.0»), а на краях
# він строго ГІРШИЙ — втрачає точність (`12345678901234.567891` → `…4.568`) і
# скочується в наукову нотацію (`0.000001` → «1.0e-06»), тобто саме те, чого на
# грошовому екрані бути не має.
#
# ✅ **Присуд founder 2026-08-14: ПЕРЕОРІЄНТУВАТИ гейт на дім форматування**
# (не знімати — знята перевірка втрачає єдиний СТАТИЧНИЙ носій, той, що
# червоніє ДО прогону).
#
# 🔴 **Але вимір 2026-08-14 показав, що периметр НЕ той, який називав пункт —
# «сім вузлів на голому `.to_f`» описує іншу множину.** Голих у Phlex-блоці
# рівно **ДВА**: `trees/show` (`z_value`) і `contracts/show` (тоді —
# `emitted_tokens`); ще **14** уже йдуть через `formatted_points`. І два
# залишки різні за родом:
#   · `z_value` — БЕЗРОЗМІРНА координата атрактора, не гроші; `.to_f` там
#     чесна форма, а дім балової точності був би хибним за визначенням;
#   · другий сайт стояв на `emitted_tokens.to_f.round(2)` — ДРУГИЙ ДІМ формули
#     `formatted_points`, написаний рукою, але на КОЛОНЦІ МОНЕТ. Звести його
#     на наявний дім не можна без брехні в імені: `formatted_points` іменований
#     балами, і його точність 2 обґрунтована КРОКОМ ДЖЕРЕЛА балів, не монет.
#     ⚠️ [ARCH.103, 2026-08-19] Колонку ЗНЯТО зі схеми; той вузол тепер читає
#     kwarg `cluster_emission` — тобто для ЦЬОГО гейта він невидимий за
#     побудовою (стеля нижче), і «голих колонок» у Phlex-блоці лишився ОДИН
#     (`z_value`). Питання одиниці/точності монет живе на самому kwarg'у.
# ⚠️ ARCH.88 ЗАКРИТО (§🗄️): нижче сказано «питання належить ARCH.88», але той
# ID більше не приймає роботи — залишок тепер належить самому ARCH.89.
# **Тобто залишок гейта гейтований не обсягом, а питанням ОДИНИЦІ — воно
# належить `ARCH.88`, і форсувати переорієнтацію зараз означало б завести
# червоне, яке нема чим чесно закрити.** Стан → `00_07` ARCH.89.
#
# 🔴 Стеля, названа тому, що вона вже коштувала двох живих сайтів: гейт стереже
# «КОЛОНКА в голому блоці», а не «BigDecimal у голому блоці» — множина береться з
# `columns_hash`/`attribute_aliases`, тож вираз без імені колонки (kwarg компонента,
# результат арифметики) для нього невидимий ЗА ПОБУДОВОЮ. Цю половину периметра
# статичним сканом не закрити — тип виразу статично не визначається, — і закриває
# її саме рантайм-хук вище, який бачить ФАКТИЧНИЙ тип у момент виводу.
#
# ⚠️ Компонентна спека сліпа до класу, поки фікстура — `OpenStruct`: той віддає
# Ruby-`Float`, тож сюїта бачить число там, де прод малює порожнечу (`04_06 §B.2` BP #14).
RSpec.describe "Phlex не друкує BigDecimal", type: :model do
  # 🔴 Множини беруться з РАНТАЙМУ, не з рукописного переліку: інакше нова
  # `decimal`-колонка чи новий аліас випадуть із периметра мовчки.
  def decimal_names
    @decimal_names ||= begin
      Rails.application.eager_load!
      cols = ActiveRecord::Base.descendants.flat_map do |m|
        begin
          next [] if m.abstract_class?
          next [] unless m.table_exists?

          m.columns_hash.filter_map { |n, c| n if c.type == :decimal } +
            m.attribute_aliases.filter_map { |from, to| from if m.columns_hash[to]&.type == :decimal }
        rescue StandardError
          []
        end
      end
      cols.uniq
    end
  end

  # Конвертори, після яких у блок їде вже НЕ BigDecimal. `\.round\b(?!\()` —
  # саме без аргументу: `round` дає Integer, `round(2)` лишає BigDecimal.
  #
  # 🔴 `formatted_points\(` — це НЕ послаблення, а перенесення ключа на
  # ЦЕНТРАЛІЗАТОР (§Guard-craft #23). One-Home точності балових величин
  # ([ARCH.88]) зробив `.to_f.round(2)` внутрішньою справою
  # `ApplicationComponent#formatted_points`, тож на сайтах виклику літеральний
  # `.to_f` зник — і гейт, ключований на ФОРМІ, почав червонити рівно ті пʼять
  # вузлів, які щойно стали правильними. Розширювати форму було б хибно:
  # неможливо матчити «цей вираз повернув Float». Ключ переїжджає на імʼя
  # методу, що ГАРАНТУЄ тип, і це строгіше — метод має власний носій
  # (`spec/quality/points_precision_home_spec.rb`), тоді як `.to_f` посеред
  # виразу нічого про решту виразу не обіцяє.
  def safe_conversion = /\.to_f|\.to_i|\.to_s|\.round\b(?!\()|sprintf|format\(|number_|formatted_points\(/

  def bare_decimal_renders
    re_col = Regexp.union(decimal_names)

    Dir.glob(Rails.root.join("app/views/**/*.rb")).flat_map { |file|
      File.readlines(file).each_with_index.flat_map { |line, idx|
        line.to_enum(:scan, /\{([^{}]*)\}/).filter_map do
          match = Regexp.last_match
          expr  = match[1]

          # `#{…}` — інтерполяція, вона кличе `to_s`, тож безпечна.
          next if match.pre_match.end_with?("#")
          # `t(".key", amount: x)` — i18n теж інтерполює значення.
          next if expr.match?(/\A\s*t\(/)
          next unless expr.match?(/(?:^|[.\s(])(#{re_col})\b/)
          next if expr.match?(safe_conversion)

          "#{file.sub("#{Rails.root}/", '')}:#{idx + 1} → #{expr.strip}"
        end
      }
    }
  end

  it "перелічує decimal-колонки з рантайму, а не з рукописного списку" do
    # Liveness: без цього прикладу порожній перелік зробив би головний гейт
    # вакуумним — «нуль порушень» означало б «нуль перевірок».
    expect(decimal_names).to include("balance", "z_value", "total_funding")
    expect(decimal_names).to include("scc_balance", "total_value") # аліаси
  end

  it "не має жодного голого decimal у Phlex-блоці" do
    expect(bare_decimal_renders).to be_empty, <<~MSG
      `decimal` у голому блоці друкується СИРОЮ точністю схеми — ці вузли
      віддають формат бази, а не той, що обрав дизайн:

      #{bare_decimal_renders.join("\n      ")}

      Лік: `.to_f` (або інтерполяція). ⚠️ `.round(2)` НЕ рятує — на BigDecimal
      він повертає BigDecimal. Дім → `04_04 §2`; різнобій точності — ARCH.88.
    MSG
  end
end
