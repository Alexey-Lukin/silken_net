# Файл несе ДВІ осі одного класу: brakeman (нижче) і rubocop (друга половина файлу).
# 🔴 [OPS.28, 2026-08-28] brakeman біжить у ДВОХ стійках — CI-джоба `scan_ruby` і блок
# `.githooks/pre-push` — і §Guard-craft #43 каже про цю конфігурацію прямо: дві стійки
# однієї перевірки розходяться МОВЧКИ, обидві зелені у власному режимі, і ніщо їх не
# порівнює. Там же названо, що прози для цього не досить: «both stances run the same
# battery» простояло в плейбуці від першого фіксу, і стійки розійшлись ще тричі після
# нього. Тому паритет тут ОБЧИСЛЮЄТЬСЯ, а не декларується коментарем — доти його
# тримали рівно два коментарі, які посилались один на одного.
#
# Чому саме прапорці, а не факт виклику. `--ensure-no-obsolete-ignore-entries` є
# НЕСУЧОЮ половиною цього гейта, і без нього обидві стійки лишаються зеленими рівно
# доти, доки протухле придушення не виринає як «новий warning» — тобто інструмент
# називає СИМПТОМ замість предмета. Саме цей хибний діагноз читали ЧОТИРИ рази
# (07-05 · 07-10 · 08-23 · 08-26), щоразу витрачаючи коміт на re-pin. Відбиток
# brakeman є SHA256 над `@code.inspect`, тобто над AST самого виразу, тож придушення
# протухає від будь-якого рефактора — включно з перейменуванням локальної змінної —
# при НЕЗМІННОМУ ризику.
#
# ✅ МУТАЦІЙНІ ДОКАЗИ ОБОХ ОСЕЙ — записані ТУТ, бо гейт без доказу дискримінації є
# твердженням про намір, а не про здатність [OPS.28]. Кожен прогін закінчувався
# побайтовим відкотом і зеленою базою:
#   brakeman-вісь · зняття `--ensure-no-obsolete-ignore-entries` з ХУКА → 3 з 4 прикладів
#     червоніють ПОІМЕННО; те саме з CI-стійки → 2; відкат → 4/0.
#   brakeman-вісь · сам прапорець доведено НА ПРЕДМЕТІ, не на формі: зсув AST одного
#     придушеного виразу дав EXIT **3**, окремий блок `== Obsolete Ignore Entries ==` і
#     `Ignored Warnings` 6→5 — тобто інструмент справді бачить протухання, а не мовчить.
#   rubocop-вісь · периметр-мінус-`config` → RED ×4 · зайвий токен у повній інвокації →
#     RED ×2 · зняття `-f github` → GREEN (подавальний прапорець вердикту не міняє, і
#     саме тому він виключений ПОІМЕННО, а не патерном «схоже на форматер»).
#   rubocop-вісь · другий виклик (`Lint/UselessAssignment` на вузькому периметрі) міряно
#     окремо: підсаджене мертве присвоєння → EXIT 1, відкат → EXIT 0.
# ⚠️ Перший прогін самої спеки був ХИБНО-ПОЗИТИВНИЙ і купив нею ж урок: анкор читав із
# хука `["--no-pager"]`, бо першим збігом виявився КОМЕНТАР із виміром ціни — тобто
# «перший збіг» є вибіркою за ПОЗИЦІЄЮ, а не за роллю. Виправлений анкор бере ВСІ
# виконувані згадки й вимагає їхньої згоди, що безкоштовно закрило сусідній клас:
# рядок довідки `Fix: …`, розійшовшись із викликом, давав би читачеві команду, яка не
# відтворює падіння.
#
# 🔒 СТЕЛІ, названі, щоб зелене не читалось ширше:
#   · спека звіряє ФОРМУ ВИКЛИКУ (множину прапорців), ніколи поведінку brakeman і
#     ніколи вміст `config/brakeman.ignore`;
#   · вона не стверджує, що хук СПРАЦЮЄ: чи він узагалі побіжить, вирішує
#     `core.hooksPath` на конкретній машині, а це стан середовища, не дерева;
#   · порядок прапорців не судиться — лише множина, бо brakeman до нього байдужий;
#   · path-gate хука (які шляхи вмикають блок) — окреме твердження й тут не перевіряється;
#   · 🔴 судяться ВСІ довгі прапорці, і серед них можуть бути ПОДАВАЛЬНІ, а не вердиктні.
#     Сьогодні таких немає, тож стеля латентна — але сусідній `rubocop` уже стоїть у CI як
#     `-f github` (GitHub-анотації), і якби він писався довгою формою `--format`, ця спека
#     назвала б розходженням те, що вердикту не міняє. Норма-дім (`00_06 §3`) свідомо каже
#     «прапорці, що ЗМІНЮЮТЬ ВЕРДИКТ», а не «побайтово»: дискримінатор — чи зняття
#     прапорця може перевернути зелене в червоне. Якщо такий прапорець тут колись
#     зʼявиться, правильний хід — ВИКЛЮЧИТИ його поіменно з порівняння, а не послабити
#     гейт: мовчазний виняток за формою («ігноруємо все, що схоже на формат») відкриє
#     рівно ту дірку, проти якої спека й стоїть.
module BrakemanStanceParity
  HOOK_SOURCE = REPO_ROOT.join(".githooks/pre-push")
  CI_SOURCE   = REPO_ROOT.join(".github/workflows/ci.yml")

  # Виконувані згадки виклику — коментарі відкидаються (див. чому нижче).
  def self.flag_sets(path)
    path.read.each_line
        .reject { |l| l.lstrip.start_with?("#") }
        .select { |l| l.match?(%r{bin/brakeman\s+--}) }
        .map { |l| l.scan(/--[a-z-]+/).sort }
  end
end

RSpec.describe BrakemanStanceParity, type: :quality do # rubocop:disable RSpec/MultipleDescribes -- дві осі свідомо в одному домі (хедер)
  # 🔴 Анкор куплений ВЛАСНИМ хибним спрацюванням цієї ж спеки, у першому ж її прогоні:
  # перший рядок хука зі збігом `bin/brakeman --` виявився не викликом, а КОМЕНТАРЕМ із
  # виміром ціни (`bin/brakeman --no-pager  3.41 / 3.46 / 4.05 с`), тож «форма виклику»
  # прочиталась як `["--no-pager"]`. Урок ширший за одрук: у файлі, який ДОКУМЕНТУЄ свою
  # команду, згадок команди завжди більше, ніж викликів, — тож «перший збіг» є вибіркою
  # за позицією, а не за роллю.
  #
  # Тому беруться ВСІ ВИКОНУВАНІ згадки (коментарі відкидаються), і вимагається, щоб усі
  # вони несли ту саму множину прапорців. Це сильніше за пін на один виклик і закриває
  # сусідній клас безкоштовно: рядок довідки «Fix: …», що розійшовся з реальним викликом,
  # дає читачеві команду, яка НЕ відтворює падіння, — і це та сама тиха брехня, лише
  # адресована людині, а не CI.
  def flag_sets(path)
    sets = described_class.flag_sets(path)
    raise "виконуваної згадки brakeman не знайдено у #{path.basename}" if sets.empty?

    sets
  end

  let(:hook_sets)  { flag_sets(described_class::HOOK_SOURCE) }
  let(:ci_sets)    { flag_sets(described_class::CI_SOURCE) }
  let(:hook_flags) { hook_sets.first }
  let(:ci_flags)   { ci_sets.first }

  it "обидві стійки взагалі мають виклик із прапорцями (ліхтар на порожню множину)" do
    # Без цього піна порівняння двох порожніх множин було б «паритетом» над порожнечею
    # — той самий клас, що «зелений на нулі прикладів».
    expect(hook_flags).not_to be_empty
    expect(ci_flags).not_to be_empty
  end

  it "усі виконувані згадки в межах ОДНОГО файлу згодні між собою" do
    # Довідка «Fix: …», що розійшлася з реальним викликом, дає читачеві команду, яка не
    # відтворює падіння — тиха брехня, адресована людині замість CI.
    expect(hook_sets.uniq.size).to eq(1),
                                   "у pre-push згадки brakeman розходяться: #{hook_sets.uniq.inspect}"
    expect(ci_sets.uniq.size).to eq(1),
                                 "у ci.yml згадки brakeman розходяться: #{ci_sets.uniq.inspect}"
  end

  it "множина прапорців ІДЕНТИЧНА в хуку і в CI" do
    expect(hook_flags).to eq(ci_flags),
                          "pre-push викликає #{hook_flags.inspect}, ci.yml — #{ci_flags.inspect}. " \
                          "Розходження стійок ТИХЕ: кожна зелена у своєму режимі, і локальне " \
                          "зелене перестає бути твердженням про CI (§Guard-craft #43)."
  end

  it "несуча половина гейта присутня в ОБОХ стійках" do
    # Прапорець судиться поіменно, а не через паритет: дві стійки можуть бути в ідеальній
    # згоді й обидві не мати його — тоді протухле придушення й далі виринатиме симптомом.
    %w[--ensure-no-obsolete-ignore-entries].each do |flag|
      expect(hook_flags).to include(flag)
      expect(ci_flags).to include(flag)
    end
  end
end

# 🔴 [OPS.28, 2026-08-30] Друга вісь того ж класу — rubocop, і його конфігурація ШИРША за
# brakeman-ову: ТРИ стійки (`pre-push` · CI-джоба `lint` · локальна смуга `config/ci.rb`)
# по ДВА вердикт-виклики в кожній — повний прогін + `Lint/UselessAssignment` на периметрі
# без `spec/` (коп глобально вимкнений СВІДОМО: живі хіти у `spec/` — фікстурні привʼязки,
# а гейт, народжений червоним, знімає перший, кому він заважає; OPS.19/OPS.33). Доти
# паритет тримали коментарі, що посилаються один на одного, — рівно та конфігурація, яку
# brakeman оплатив спекою вище після трьох тихих розходжень (§Guard-craft #43).
#
# 🔒 СТЕЛІ понад успадковані від brakeman-осі (форма ≠ поведінка, спрацювання хука — стан
# машини, path-gate окремо):
#   · порядок токенів СУДИТЬСЯ: це пін канонічної форми запису, не семантики rubocop
#     (він до порядку байдужий) — перестановка периметра впаде як розходження, і лік
#     їй — переписати в канонічному порядку, не послабити гейт;
#   · echo-рядки виключені РАЗОМ з коментарями: fix-довідка хука легітимно несе `-a`
#     (автокорект — порада ПІСЛЯ падіння, не вердикт-виклик), тож судити її на рівність
#     із вердиктом хибно; її власний дрейф цей гейт не стереже;
#   · availability-проба `bundle exec rubocop --version` не матчиться патерном
#     `bin/rubocop` — і це правильно: вона вердикту не несе.
module RubocopStanceParity
  HOOK_SOURCE  = REPO_ROOT.join(".githooks/pre-push")
  CI_SOURCE    = REPO_ROOT.join(".github/workflows/ci.yml")
  LOCAL_SOURCE = REPO_ROOT.join("config/ci.rb")
  STANCES = { "pre-push" => HOOK_SOURCE, "ci.yml" => CI_SOURCE, "config/ci.rb" => LOCAL_SOURCE }.freeze

  # Подавальні токени (вердикту не міняють) — виключення ПОІМЕННЕ, за нормою `00_06 §3`
  # («прапорці, що ЗМІНЮЮТЬ ВЕРДИКТ», не побайтово): `-f github` = формат анотацій для
  # PR-вʼю. Довга форма названа теж, щоб перепис короткої в довгу не зіграв розходженням.
  FEED_TOKENS = [ %w[-f github], %w[--format github] ].freeze

  def self.invocations(path)
    path.read.each_line
        .reject { |l| l.lstrip.start_with?("#") || l.match?(/\becho\b/) }
        .filter_map { |l| l[%r{bin/rubocop([^"');]*)}, 1]&.split }
        .map { |tokens| FEED_TOKENS.reduce(tokens) { |t, pair| drop_pair(t, pair) } }
  end

  def self.drop_pair(tokens, pair)
    idx = tokens.each_cons(pair.size).to_a.index(pair)
    idx ? tokens.dup.tap { |t| t.slice!(idx, pair.size) } : tokens
  end
end

RSpec.describe RubocopStanceParity, type: :quality do
  # { назва стійки => [повна інвокація, dead-code інвокація] }
  let(:stances) do
    described_class::STANCES.transform_values do |path|
      invs = described_class.invocations(path)
      [ invs.reject { |t| t.include?("--only") }, invs.select { |t| t.include?("--only") } ]
    end
  end

  it "кожна з трьох стійок несе РІВНО дві вердикт-інвокації: повну + dead-code" do
    # Ліхтар РОЗМІРУ множини, не лише непорожності: паритет над недобраною вибіркою
    # (стійка, де парсер побачив один виклик із двох) був би зеленим про півправди.
    stances.each do |name, (full, dead)|
      expect(full.size).to eq(1), "#{name}: повних інвокацій #{full.size}, очікувалась 1: #{full.inspect}"
      expect(dead.size).to eq(1), "#{name}: dead-code інвокацій #{dead.size}, очікувалась 1: #{dead.inspect}"
    end
  end

  it "повна інвокація ІДЕНТИЧНА в усіх трьох стійках (по модулю подавальних токенів)" do
    forms = stances.transform_values { |(full, _)| full.first }
    expect(forms.values.uniq.size).to eq(1),
                                      "повний прогін розходиться між стійками: #{forms.inspect}"
  end

  it "dead-code інвокація (коп + периметр) ІДЕНТИЧНА в усіх трьох стійках" do
    # Периметр `app lib scripts config` — вердикт-несуча половина цього виклику
    # (§Guard-craft #44: розходження живе не лише в тому, ЩО біжить, а й над ЧИМ).
    forms = stances.transform_values { |(_, dead)| dead.first }
    expect(forms.values.uniq.size).to eq(1),
                                      "dead-code виклик розходиться між стійками: #{forms.inspect}"
  end

  it "несуча половина поіменно: коп і периметр без spec/ у кожній стійці" do
    # Аналог brakeman-піна `--ensure-no-obsolete…`: три стійки можуть бути в ідеальній
    # згоді й УСІ разом загубити периметр — тоді паритет зелений над вихолощеним викликом.
    stances.each do |name, (_, dead)|
      tokens = dead.first
      expect(tokens).to include("--only", "Lint/UselessAssignment", "app", "lib", "scripts", "config"),
                        "#{name}: dead-code виклик утратив коп або периметр: #{tokens.inspect}"
      expect(tokens).not_to include("spec"),
                            "#{name}: spec/ у периметрі — гейт стане народженим червоним (OPS.19)"
    end
  end
end
