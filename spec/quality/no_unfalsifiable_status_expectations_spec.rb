require "rails_helper"

# Заборона прикладів, які приймають 5xx як припустимий результат
# (`expect(response.status).to be_in([ 200, 500 ])` і рідня).
#
# 🔴 Це не стильова преференція, а вимкнений детектор. Такий приклад зелений і
# коли шлях працює, і коли сервер падає, тобто не може впасти В ПРИНЦИПІ — а
# CI-зелень читається як доказ. Виміряні наслідки в цьому дереві ([`TEST.10`]):
# сторінка завантаження прошивки віддавала 500 і не рендерила форми взагалі,
# і приклад був зелений САМЕ через це; 11 non-safe дій віддавали 200 без
# редиректу пів року ([`SEC.25`]); а приклад із назвою «missing family» ніколи
# не доходив до валідації — падав на UID-guard'і, і множина {422, 500} разом
# із хеджем `errors || error` не давала цього побачити.
#
# 🔴 Походження, через яке клас відростає сам: усі екземпляри народились у
# комітах, чия мета названа в заголовку («Increase coverage to 96%»). Приклад
# ходить по коду (покриття росте) і не може впасти (CI зелений) — тобто це був
# ОПТИМАЛЬНИЙ інструмент для поставленої метрики. Поріг покриття тримається
# HARD, отже прибрати вакуумний приклад не можна, не замінивши справжнім: тиск,
# що створив дефект, став його бронею. Гейт розриває саме цю петлю.
#
# 🔒 Стеля — чотири речі, яких він НЕ бачить, і мовчання тут означало б «перевірено».
#   1. Лише ЛІТЕРАЛЬНА множина `be_in([...])` у не-коментованому рядку. Те саме,
#      зібране через змінну, `satisfy`-блок чи матчер-ланцюг, повз нього пройде.
#   2. 🔴 Лише множина, що ПЕРЕТИНАЄ КЛАСИ статусів. Хедж усередині одного класу
#      невидимий за побудовою — `be_in([ 403, 429 ])` у `rack_attack_spec`
#      не розрізняє «спрацював названий throttle» і «Fail2Ban віддав 403 з
#      401-их», тобто правило можна видалити, і приклад лишиться зеленим. Це
#      семантика, не форма: щоб її побачити, треба знати, які механізми дають
#      кожен код (→ [`00_07`](00_07_Action_Plan_Tracker) TEST.10).
#   3. Лише вісь статусу. `have_http_status(:redirect)` (будь-який 3xx — саме воно
#      сховало 302-замість-303, [`UI.7`]), голий пін на статус там, де назва
#      обіцяє вміст, `not_to raise_error` як єдине твердження прикладу, чи
#      `expect(html).to be_present` як доказ рендеру — для нього невидимі.
#   4. Коментарі свідомо пропускаються, і це НЕ послаблення: розбір знятого
#      дефекту цитує його форму, тож без пропуску гейт червонів би від власної
#      документації. Дзеркальна ціна — прозовий літерал тримає файл
#      грепо-позитивним для РУЧНОГО виміру, тому в цьому дереві стару форму
#      переказують («множина {200, 500}»), а не цитують.
RSpec.describe "no unfalsifiable status expectations" do # rubocop:disable RSpec/DescribeClass
  let(:scanned_files) { Dir[Rails.root.join("spec/**/*_spec.rb")].sort }

  let(:offenders) do
    scanned_files.flat_map do |path|
      File.readlines(path).each_with_index.filter_map do |line, idx|
        next if line.lstrip.start_with?("#")

        set = line[/be_in\(\s*\[([^\]]*)\]/, 1]
        next if set.nil?

        codes = set.scan(/\b\d{3}\b/).map(&:to_i).select { |c| c.between?(100, 599) }
        next if codes.size < 2
        # Один КЛАС статусу = одне твердження про долю запиту. Множина, що
        # перетинає класи, приймає і успіх, і відмову — тобто не тверджує нічого.
        next if codes.map { |c| c / 100 }.uniq.one?

        "#{Pathname.new(path).relative_path_from(Rails.root)}:#{idx + 1}"
      end
    end
  end

  # Без цього «0 порушень» могло б означати «glob дивиться не туди».
  it "is a live check (the spec tree is non-empty and scannable)" do
    expect(scanned_files.size).to be > 100,
      "сканер знайшов замало spec-файлів — glob дивиться не туди"
  end

  it "never lets a status expectation span two status classes" do
    expect(offenders).to be_empty, <<~MSG
      множина статусів, що перетинає класи (2xx/3xx/4xx/5xx), не може впасти:
      приклад зелений і коли шлях працює, і коли ні. Тверджуй ОДИН статус +
      `media_type` + вміст (`04_06 §B.2` #15); якщо гілка справді має віддати
      5xx — тверджуй його точно (`have_http_status(:internal_server_error)`).
      А коли два коди дає ДВА РІЗНІ механізми — різни їх ціллю редіректу,
      флешем або тілом, бо сам статус тут не дискримінує.
      Знайдено: #{offenders.join(', ')}
    MSG
  end
end
