# Shared helpers для браузерного (feature) шару.
#
# Конвенція та сама, що в `PhlexComponentHelper`: модуль включається САМ у все
# під `spec/features/` через metadata-хук унизу файлу — окремо підключати не треба.
#
# 🧱 **Що належить цьому шару, а що ні — правило живе в каноні `04_06 §B.1.4`**
# (критерій одним рядком: приклад виправданий лише тоді, коли нижче він
# неможливий У ПРИНЦИПІ; дзеркальна половина — доказовне request-спекою сюди НЕ
# дублюється). Тут його не переказуємо, щоб не завести другий дім.
#
# ─────────────────────────────────────────────────────────────────────────────
# ⚠️ СТЕЛІ ШАРУ (виміряні, не припущені) — читай, перш ніж діагностувати «флейк»
# ─────────────────────────────────────────────────────────────────────────────
#
#   1. Capybara скоупить пошук у `/html/body`, тож `have_css("html.dark")` не
#      матчить НІКОЛИ. Пінься за вузол усередині `body`, який мутує контролер.
#   2. `evaluate_script` НЕ чекає нічого — на відміну від матчерів Capybara. Тож
#      для будь-якої асинхронної зміни (Turbo-візит, морф, відповідь стріму)
#      спершу дочекайся DOM-зміни через `have_css`, і лише ПОТІМ читай скриптом,
#      інакше прочитаєш стан ДО неї. Живий приклад — перемикання локалі в
#      `dashboard_browser_smoke_spec`: спершу `have_css` на локалізований
#      `aria-label`, і лише потім читання `documentElement.lang`.
#   3. ⚠️ Тут стояло «Leaflet пінниться на ЗОВНІШНІЙ CDN, тож сценарії на мапу
#      недосяжні» — знято 2026-08-03 як ХИБНЕ, і воно ж було третім домом того
#      самого діагнозу. Причин було дві, обидві виміряні: недосяжний CDN валив
#      статичний `import` і разом з ним УВЕСЬ контролер (не лише мапу), а
#      головна — `nodeTargetConnected` приходить РАНІШЕ за `connect()`, тож
#      перше ж геолоковане дерево кидало виняток до створення `this.map`.
#      Модуль тепер локальний, ініціалізація ідемпотентна, приклад на мапу живе
#      в `dashboard_browser_smoke_spec.rb`.
#   3а. 🔴 Успадкована звідти пастка, яка коштує години: локальний
#      `public/assets/.manifest.json` тримає Propshaft на **Static**-резолвері.
#      ГУЧНА половина: після будь-якого нового піна ВСІ браузерні приклади
#      падають на логіні (asset не в манифесті → stub гасить теги → сторінка
#      без JS), і симптом виглядає як зламана автентифікація.
#      🔴 ТИХА половина, дорожча (виміряно 2026-08-17): той самий резолвер
#      віддає ЗАСТАРІЛИЙ дайджест CSS — приклади не падають, а ПРОХОДЯТЬ,
#      міряючи знімок стилів довільної давнини. Свіжий `tailwindcss:build`
#      до браузера не доходить, тож прилад червонить на вже полагодженому коді.
#      ✅ Лік — ВИДАЛИТИ `public/assets/`, не оновлювати її: CI прекомпіляції
#      свідомо не робить (`ci.yml`, крок `feature-test`), а оновлений манифест
#      лишає локальний прогін на резолвері, якого в CI немає, і протухає при
#      наступній правці CSS. `assets:precompile` доречний, лише коли предметом
#      є САМЕ Static-шлях. Дім класу → `04_06 §B.1.4`.
#   4. `FEATURE_TEST=1` вимикає SimpleCov-поріг — власний прогін цього шару дає
#      ≈0% глобального покриття, тож без прапорця гейт хибно впав би (`04_06 §B.3`).
#   5. 🔴 Не «лагодь» приклад моком: замоканий Stimulus доводив би, що працює мок,
#      а не застосунок — тобто рівно те, заради чого шар і існує, зникає.
#
module FeatureHelper
  # Логін через СПРАВЖНЮ форму, а не через підміну сесії.
  #
  # 🔴 Саме форма, і це не церемонія: підміна сесії обійшла б `establish_session`,
  # тобто той самий salt-стемп (`session[:ps]`, SEC.16), від якого залежить
  # половина сценаріїв цього шару — включно з «сесія протухла». Приклад, що
  # логіниться в обхід, довів би поведінку, якої в проді немає.
  #
  # ⚠️ Поле форми зветься `email`, а колонка — `email_address`: форма йде через
  # `form_with url:` без моделі, тож імена полів свої. Розбіжність реальна.
  #
  # Хелпер САМ чекає на завершення візиту — це синхронізація, а не твердження,
  # тож приклад лишається вільним пінити те, заради чого написаний. Без цього
  # кожен наступний приклад повторював би `have_current_path` як ритуал.
  def sign_in_as(user, password:)
    visit "/login"
    fill_in "email", with: user.email_address
    fill_in "password", with: password
    click_button type: "submit"

    expect(page).to have_current_path(%r{/dashboard}), "логін не довів до дашборда"

    # 🔴 [UI.3] Шлях — НЕ доказ, що сторінка жива: 403 і 500 рендеряться на ТОМУ Ж
    # шляху, тож `have_current_path` пропускає обидва, а кожен наступний крок прикладу
    # мовчки міряє `Errors::Page`. У всьому `spec/features/` пінів на статус було
    # НУЛЬ, тобто клас накривав усі браузерні приклади разом. Тут він знімається
    # ОДНИМ місцем, бо через цей хелпер проходить кожен логін.
    expect(page.status_code).to eq(200),
                                "дашборд віддав #{page.status_code} — приклад далі міряв би сторінку помилки"
  end

  # [UI.3] Візит із перевіркою, що сторінка справді відкрилась. Прямий `visit` цього
  # не каже: гейтована сторінка від негейтованого актора віддає 403 на СВОЄМУ шляху,
  # тож `have_current_path` після неї зелений — саме так probe приладу контрасту
  # колись зібрав нуль пар і не поскаржився.
  def visit_ok(path)
    visit path

    expect(page.status_code).to eq(200),
                                "#{path} віддав #{page.status_code} — далі приклад міряв би `Errors::Page`"
  end
end

RSpec.configure do |config|
  config.include FeatureHelper, file_path: %r{spec/features/}
end
