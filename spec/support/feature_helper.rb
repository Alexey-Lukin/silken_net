# Shared helpers для браузерного (feature) шару.
#
# Конвенція та сама, що в `PhlexComponentHelper`: модуль включається САМ у все
# під `spec/features/` через metadata-хук унизу файлу — окремо підключати не треба.
#
# 🧱 **Що належить цьому шару, а що ні — правило живе в каноні `04_06 §B.1.4`**
# (критерій одним рядком: приклад виправданий лише тоді, коли нижче він
# неможливий У ПРИНЦИПІ; дзеркальна половина — доказовне request-спекою сюди НЕ
# дублюється). Тут його не переказуємо, щоб не завести другий дім.
#
# ─────────────────────────────────────────────────────────────────────────────
# ⚠️ СТЕЛІ ШАРУ (виміряні, не припущені) — читай, перш ніж діагностувати «флейк»
# ─────────────────────────────────────────────────────────────────────────────
#
#   1. Capybara скоупить пошук у `/html/body`, тож `have_css("html.dark")` не
#      матчить НІКОЛИ. Пінься за вузол усередині `body`, який мутує контролер.
#   2. `theme#toggle` іде через `document.startViewTransition` — застосування
#      асинхронне. Спершу дочекайся DOM-зміни через `have_css`, і лише ПОТІМ
#      читай `evaluate_script`, інакше прочитаєш стан ДО транзиції.
#   3. Leaflet пінниться на ЗОВНІШНІЙ CDN (`config/importmap.rb` → `ga.jspm.io`),
#      тож у тесті модуль не приїжджає і сценарії на мапу недосяжні (`00_07` TEST.7).
#   4. `FEATURE_TEST=1` вимикає SimpleCov-поріг — власний прогін цього шару дає
#      ≈0% глобального покриття, тож без прапорця гейт хибно впав би (`04_06 §B.3`).
#   5. 🔴 Не «лагодь» приклад моком: замоканий Stimulus доводив би, що працює мок,
#      а не застосунок — тобто рівно те, заради чого шар і існує, зникає.
#
module FeatureHelper
  # Логін через СПРАВЖНЮ форму, а не через підміну сесії.
  #
  # 🔴 Саме форма, і це не церемонія: підміна сесії обійшла б `establish_session`,
  # тобто той самий salt-стемп (`session[:ps]`, SEC.16), від якого залежить
  # половина сценаріїв цього шару — включно з «сесія протухла». Приклад, що
  # логіниться в обхід, довів би поведінку, якої в проді немає.
  #
  # ⚠️ Поле форми зветься `email`, а колонка — `email_address`: форма йде через
  # `form_with url:` без моделі, тож імена полів свої. Розбіжність реальна.
  #
  # Хелпер САМ чекає на завершення візиту — це синхронізація, а не твердження,
  # тож приклад лишається вільним пінити те, заради чого написаний. Без цього
  # кожен наступний приклад повторював би `have_current_path` як ритуал.
  def sign_in_as(user, password:)
    visit "/login"
    fill_in "email", with: user.email_address
    fill_in "password", with: password
    click_button type: "submit"

    expect(page).to have_current_path(%r{/dashboard}), "логін не довів до дашборда"
  end
end

RSpec.configure do |config|
  config.include FeatureHelper, file_path: %r{spec/features/}
end
