  }.freeze

  MEASURED_KEYS   = CONTOURS.values.flat_map { |c| c[:paths].keys }.freeze
  CLASSIFIED_KEYS = (MEASURED_KEYS + WAVES.values.flat_map { |w| w[:routes] }).freeze

  # Конкретні шляхи одного контуру. Спека кличе САМЕ це — тож «виміряно» в
  # реєстрі не може розійтися з тим, що прилад реально відкриває.
  def self.paths_for(contour, ctx)
    CONTOURS.fetch(contour)[:paths].values.map { |builder| builder.call(ctx) }
  end
