      # Стеля лишається лексичною: новий відтінок вписується сюди ЯВНО.
      class_tokens: [ "text-emerald-900/5", "text-gaia-text-muted/5" ],
      why: "тлові гліфи-watermark (≈1.02:1) — вони не несуть інформації, потрібної " \
