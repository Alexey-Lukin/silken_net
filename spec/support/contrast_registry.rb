# [UI.3] ДОКУМЕНТ контуру контрастності: які сторінки прилад міряє, які ще ні —
# і чому кожна з решти лежить поза виміром.
#
# 🔴 Навіщо він узагалі, коли прилад уже працює. Прилад міряє РІВНО ті сторінки,
# які йому дали, тож перелік є частиною ВИМІРУ, а не його обстановкою — і це вже
# коштувало хибного присуду: шість сторінок дали «темна тема майже чиста, одна
# провальна пара», а одинадцять — сімдесят. Ті шість не були випадковими: це
# сторінки, що вже мали фікстуру, тобто систематично здоровіші за середнє.
# Доти перелік жив літералом усередині кожної спеки, тож НОВИЙ маршрут не
# зʼявлявся у вимірі ніколи й нічого про це не казало. Тепер популяція
# деривується з `routes.rb`, а кожен її член мусить бути КЛАСИФІКОВАНИЙ тут.
#
# 🧱 ФОРМА — курована мапа, що ЛИШЕ СКОРОЧУЄТЬСЯ (взірець — `browser_contour_registry`).
# Хвиля порожніє → її запис зникає. Це вибір проти двох гірших:
#   · skip-list, у який дописують винятки, гниє тихо й за півроку стає політикою;
#   · «виміряти всі 60 одразу» — контур підіймає реальний браузер на кожну
#     сторінку, тож ціна лінійна, а користь падає: більшість сторінок ділить
#     ті самі токени, і корінь уже полічено (`contrast_root_tokens_spec`).
#
# ⚠️ Ключ — `контролер#екшен`, свідомо БЕЗ шляху: шлях несе параметри й
# змінюється від переіменування ресурсу, а ключ переживає і те, і те. Дублікати
# шляхів під одним ключем (`/` та `/dashboard`) згортаються за побудовою.
#
# 🔴 КЛАСИФІКАЦІЯ — ДЕКЛАРАЦІЯ ЛЮДИНИ, не висновок екстрактора, і саме тому
# доводиться, а не вгадується. Мій власний здогад про «машинні» ендпоінти був
# ХИБНИЙ на СЕМИ з одинадцяти: `wallets#balance`/`#metadata`,
# `actuators#command_status` і `users#me` віддають HTML через `respond_to`, а
# `wallets#transaction_status`, `blockchain_transactions#on_chain` і
# `maintenance_records#photos` — HTML-фрагменти для Turbo. Справді JSON-only
# лише чотири. Тобто «очевидно машинний» тут = сім поверхонь, тихо вилучених із
# контуру назавжди. Класифікуючи новий маршрут, ВІДКРИЙ екшен.
#
# ⚠️ Ці чотири лежать у хвилях СВОЇХ РОДИН, а не в окремій «я помилився»-хвилі:
# перша редакція завела для них власну, і в неї вийшов РОЗМИТИЙ `back` («разом
# із родиною»), тоді як родини мають різні тригери. Провенанс помилки — запис
# у шапці; хвиля мусить групувати за ПРИЧИНОЮ звільнення, не за історією.
#
# 🔒 Чого цей реєстр НЕ вирішує (зелений ≠ «поверхня доступна»):
#   · він про ПОПУЛЯЦІЮ, не про пороги — числа й буксети живуть у `contrast_audit`;
#   · один розмір вікна: мобільна розмітка має власну (`td::before` card-flip);
#   · СТАНИ (`:hover`/`:focus-visible`/`::placeholder`/`:disabled`) не покриті
#     жодним контуром — статичний знімок їх не має за побудовою;
#   · він не знає, чи сторінка ДОСЯЖНА для актора: `tree_families` гейтовані
#     `authorize_super_admin!` і для звичайного адміна віддадуть `Errors::Page`
#     на тому ж шляху — тобто мовчазний нуль пар при зеленому піні на шлях.
